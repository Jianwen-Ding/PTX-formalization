#!/usr/bin/env python3
"""Generate tests/mma-m8n8k4-f16.ptx (mma.sync.aligned.m8n8k4 with .f16 A / B: four independent 8x8x4 products by
quad pairs, every .alayout / .blayout and legal .dtype / .ctype) and tests/mma-f64-rnd.ptx (f64 mma with the
rounding modifiers .rn / .rz / .rm / .rp) against an exact model.  The fragment layouts are transcribed from the
PTX ISA 9.3 text (9.7.15.5.1, Figures 46-52; 9.7.15.5.2-3 for f64) independently of the Sail model.
usage: gen_mma_m8n8k4.py [SEED]"""
import random, sys
from fractions import Fraction
here = __file__.rsplit('/', 1)[0]
src = open(here + '/gen_mma.py').read().split('cases = []')[0]
sys.argv = [sys.argv[0]] + sys.argv[1:2]
exec(compile(src, 'gen_mma_prefix', 'exec'))
random.seed(int(sys.argv[1]) if len(sys.argv) > 1 else 884)
h = lambda xs: ", ".join(str(x) for x in xs)

def bits_round(ty, v, mode):
    """Fraction -> bits of ty rounded with mode (v != 0)"""
    w = {'f16': 16, 'f32': 32, 'f64': 64}[ty]
    assert v != 0
    sg = 1 if v < 0 else 0
    return (sg << (R.CW[w] - 1)) | R.round_mag(abs(v), 0, mode, sg, w)

# ---------------------------------------------------------------- m8n8k4 .f16 (ISA 9.7.15.5.1)
# For lane l: MMA computation q = (l % 16) // 4 (lanes 0-3 + 16-19 compute product 0, ...); "low group" l < 16.
def frag_a(l, i, col):           # Figures 46 / 47
    hi = 0 if l < 16 else 4
    return (i % 4 + hi, l % 4) if col else (l % 4 + hi, i)
def frag_b(l, i, col):           # Figures 48 / 49
    hi = 0 if l < 16 else 4
    return (i, l % 4 + hi) if col else (l % 4, i + hi)
def frag_c(l, i, ty):            # Figure 50 (.f16), Figures 51 / 52 (.f32)
    hi = 0 if l < 16 else 4
    if ty == 'f16': return (l % 4 + hi, i)
    return ((l & 1) + (i & 2) + hi, (i & 4) + (l & 2) + (i & 1))

def check_layouts():
    for q in range(4):
        lanes = [l for l in range(32) if (l % 16) // 4 == q]
        for col in (False, True):
            assert sorted(frag_a(l, i, col) for l in lanes for i in range(4)) == [(r, c) for r in range(8) for c in range(4)]
            assert sorted(frag_b(l, i, col) for l in lanes for i in range(4)) == [(r, c) for r in range(4) for c in range(8)]
        for ty in ('f16', 'f32'):
            assert sorted(frag_c(l, i, ty) for l in lanes for i in range(8)) == [(r, c) for r in range(8) for c in range(8)]
check_layouts()

def pack(vals, ew):
    per = 32 // ew
    return [sum(vals[r * per + j] << (ew * j) for j in range(per)) for r in range(len(vals) // per)]

def m884_case(acol, bcol, dt, ct):
    A = [{(r, c): rand_float_bits('f16') for r in range(8) for c in range(4)} for q in range(4)]
    B = [{(r, c): rand_float_bits('f16') for r in range(4) for c in range(8)} for q in range(4)]
    C = [{(r, c): rand_float_bits(ct) for r in range(8) for c in range(8)} for q in range(4)]
    D = []
    for q in range(4):
        Dq = {}
        for r in range(8):
            for c in range(8):
                s = fval(ct, C[q][(r, c)]) + sum(fval('f16', A[q][(r, k)]) * fval('f16', B[q][(k, c)]) for k in range(4))
                Dq[(r, c)] = to_bits(dt, s)
        D.append(Dq)
    ewc, ewd = (16 if ct == 'f16' else 32), (16 if dt == 'f16' else 32)
    fa, fb, fc, fd = [], [], [], []
    for l in range(32):
        q = (l % 16) // 4
        fa.append(pack([A[q][frag_a(l, i, acol)] for i in range(4)], 16))
        fb.append(pack([B[q][frag_b(l, i, bcol)] for i in range(4)], 16))
        fc.append(pack([C[q][frag_c(l, i, ct)] for i in range(8)], ewc))
        fd.append(pack([D[q][frag_c(l, i, dt)] for i in range(8)], ewd))
    return fa, fb, fc, fd

def emit(path, title, kernels):
    """kernels: list of (instruction text, regs A, B, C, D (per lane lists), register width)"""
    L = [f"// GENERATED by scripts/gen_mma_m8n8k4.py -- {title}", ".version 8.0\n.target sm_90\n.address_size 64\n"]
    tail = []
    for kk, (ins, fa, fb, fc, fd, wb) in enumerate(kernels):
        na, nb, nc, nd = len(fa[0]), len(fb[0]), len(fc[0]), len(fd[0])
        sz = wb // 8
        L.append(f".visible .entry k{kk}(.param .u64 pa, .param .u64 pb, .param .u64 pc, .param .u64 po)\n{{\n"
                 f"    .reg .b32 %r0; .reg .b64 %rd<2>; .reg .b{wb} %A<{na}>, %B<{nb}>, %C<{nc}>, %D<{nd}>;\n    mov.u32 %r0, %tid.x;")
        for nm, cnt, par in (('A', na, 'pa'), ('B', nb, 'pb'), ('C', nc, 'pc')):
            L.append(f"    ld.param.u64 %rd0, [{par}]; mul.wide.u32 %rd1, %r0, {cnt * sz}; add.s64 %rd0, %rd0, %rd1;")
            for i in range(cnt): L.append(f"    ld.global.b{wb} %{nm}{i}, [%rd0+{i * sz}];")
        vec = lambda p, c: "{" + ", ".join(f"%{p}{i}" for i in range(c)) + "}"
        L.append(f"    {ins} {vec('D', nd)}, {vec('A', na)}, {vec('B', nb)}, {vec('C', nc)};")
        L.append(f"    ld.param.u64 %rd0, [po]; mul.wide.u32 %rd1, %r0, {nd * sz}; add.s64 %rd0, %rd0, %rd1;")
        for i in range(nd): L.append(f"    st.global.b{wb} [%rd0+{i * sz}], %D{i};")
        L.append("    ret;\n}\n")
        flat = lambda f: h(x for lane in f for x in lane)
        u = f"u{wb}"
        tail.append(f".buffer A{kk} .{u} = {{ {flat(fa)} }};\n.buffer B{kk} .{u} = {{ {flat(fb)} }};\n.buffer C{kk} .{u} = {{ {flat(fc)} }};")
        tail.append(f".buffer O{kk} .{u} [{32 * nd}];\n.launch k{kk} <<< 1, 32 >>> (A{kk}, B{kk}, C{kk}, O{kk});\n.expect O{kk} .{u} = {{ {flat(fd)} }};")
    open(path, 'w').write("\n".join(L + tail) + "\n")

kernels = []
for dt, ct in (('f16', 'f16'), ('f32', 'f16'), ('f32', 'f32')):       # .ctype .f32 needs .dtype .f32 (9.7.15.5.14)
    for acol in (False, True):
        for bcol in (False, True):
            fa, fb, fc, fd = m884_case(acol, bcol, dt, ct)
            lay = f"{'col' if acol else 'row'}.{'col' if bcol else 'row'}"
            kernels.append((f"mma.sync.aligned.m8n8k4.{lay}.{dt}.f16.f16.{ct}", fa, fb, fc, fd, 32))
emit('tests/mma-m8n8k4-f16.ptx', "mma.m8n8k4 with .f16 A / B vs. an exact model (ISA 9.7.15.5.1).", kernels)

# ---------------------------------------------------------------- f64 rounding modifiers (ISA 9.7.15.5.14)
def f64_case(shape, mode):
    m, n, k = [int(x) for x in shape[1:].replace('n', ' ').replace('k', ' ').split()]
    LA, LB, LC = check_bij('A', shape, 64), check_bij('B', shape, 64), check_bij('C', shape, 64)
    while True:
        A = {p: rand_float_bits('f64') | 1 for p in LA.values()}         # odd significands: inexact sums
        B = {p: rand_float_bits('f64') | 1 for p in LB.values()}
        C = {p: rand_float_bits('f64') | 1 for p in LC.values()}
        S = {(r, c): fval('f64', C[(r, c)]) + sum(fval('f64', A[(r, kk)]) * fval('f64', B[(kk, c)]) for kk in range(k))
             for r in range(m) for c in range(n)}
        if all(v != 0 for v in S.values()): break
    D = {p: bits_round('f64', v, mode) for p, v in S.items()}
    regs = lambda L, V, cnt: [[V[L[(l, i)]] for i in range(cnt)] for l in range(32)]
    return regs(LA, A, m * k // 32), regs(LB, B, k * n // 32), regs(LC, C, m * n // 32), regs(LC, D, m * n // 32)

kernels = []
for shape in ('m8n8k4', 'm16n8k8'):
    for mode in ('rn', 'rz', 'rm', 'rp'):
        fa, fb, fc, fd = f64_case(shape, mode)
        kernels.append((f"mma.sync.aligned.{shape}.row.col.f64.f64.f64.f64.{mode}", fa, fb, fc, fd, 64))
emit('tests/mma-f64-rnd.ptx', "f64 mma.sync with the rounding modifiers .rn / .rz / .rm / .rp.", kernels)
print("mma-m8n8k4-f16: 12 kernels, mma-f64-rnd: 8 kernels")
