#!/usr/bin/env bash
# Build GPGPU-Sim's PTX functional core (parser + functional simulator) and
# the difftest driver, WITHOUT any NVIDIA software.
#
#   scripts/difftest_gpgpusim/build.sh [WORKDIR]
#
# WORKDIR (default: $DIFFTEST_GPGPUSIM_WORK or ./_gpgpusim_build) receives the
# pinned GPGPU-Sim checkout, generated parser sources, objects and the binary
# WORKDIR/gpgpusim-ptx.  Set GPGPUSIM_SRC=/path/to/existing/checkout to use an
# existing clone (read-only; its HEAD must be the pinned commit) instead of
# cloning from GitHub.
# Parallelism defaults to -j2 (JOBS=n to change).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORK="${1:-${DIFFTEST_GPGPUSIM_WORK:-$PWD/_gpgpusim_build}}"
JOBS="${JOBS:-2}"
REPO_URL=https://github.com/gpgpu-sim/gpgpu-sim_distribution
COMMIT=c3eeb6d19016960ab66789efdd8a3200cc30222a   # gpgpu-sim_distribution "dev"
CXX="${CXX:-g++}"

for tool in git bison flex "$CXX" make patch; do
  command -v "$tool" >/dev/null || { echo "missing tool: $tool" >&2; exit 1; }
done

mkdir -p "$WORK"
WORK="$(cd "$WORK" && pwd)"
if [ -n "${GPGPUSIM_SRC:-}" ] && [ -d "$GPGPUSIM_SRC" ]; then
  # An existing checkout: used read-only, it must be at the pinned commit.
  SRC="$(cd "$GPGPUSIM_SRC" && pwd)"
  head="$(git -C "$SRC" rev-parse HEAD)"
  if [ "$head" != "$COMMIT" ]; then
    echo "$SRC is at $head, expected $COMMIT" >&2; exit 1
  fi
else
  SRC="$WORK/gpgpusim"
  if [ ! -d "$SRC/.git" ]; then
    git clone --quiet --no-checkout "$REPO_URL" "$SRC"
  fi
  git -C "$SRC" checkout --quiet --force "$COMMIT"
fi

# ---------------------------------------------------------------------------
# Private copy of exactly the files we compile or include.  Files derived
# from the CUDA toolkit (GPGPU-Sim COPYRIGHT, NOTE 1) are NOT copied:
#   libcuda/cuda_runtime_api.cc   -- not used, our driver replaces it
#   libcuda/cuda_api.h            -- NVIDIA cuda.h copy, not used
#   src/cuda-sim/cuda-math.h      -- replaced by stubs/cuda-sim/cuda-math.h
# src/cuda-sim/decuda_pred_table/ (derived from decuda) is not compiled
# either; its header is replaced by a stub and its one function is stubbed.
# ---------------------------------------------------------------------------
T="$WORK/tree"     # what is compiled (only rewritten files change)
S="$WORK/stage"    # fresh upstream copy + patches, synced into $T
rm -rf "$S"
mkdir -p "$S/src/cuda-sim/decuda_pred_table" "$S/src/gpgpu-sim" "$S/libcuda"
cp "$SRC/version" "$S/"
cp "$SRC"/src/*.h "$SRC/src/abstract_hardware_model.cc" \
   "$SRC/src/option_parser.cc" "$S/src/"
cp "$SRC"/src/*.tup "$S/src/" 2>/dev/null || true
cp "$SRC"/src/gpgpu-sim/*.h "$S/src/gpgpu-sim/"
cp "$SRC"/src/gpgpu-sim/*.tup "$S/src/gpgpu-sim/" 2>/dev/null || true
for f in cuda-sim.cc cuda-sim.h cuda_device_printf.cc cuda_device_printf.h \
         cuda_device_runtime.cc cuda_device_runtime.h half.h half.hpp \
         instructions.cc memory.cc memory.h opcodes.def opcodes.h \
         ptx-stats.cc ptx-stats.h ptx.l ptx.y ptx_ir.cc ptx_ir.h \
         ptx_loader.cc ptx_loader.h ptx_parser.cc ptx_parser.h \
         ptx_sim.cc ptx_sim.h ptxinfo.l ptxinfo.y; do
  cp "$SRC/src/cuda-sim/$f" "$S/src/cuda-sim/"
done
cp "$HERE/stubs/decuda_pred_table.h" "$S/src/cuda-sim/decuda_pred_table/"
cp "$HERE/stubs/cuda-sim/cuda-math.h" "$S/src/cuda-sim/cuda-math.h"
for f in gpgpu_context.h cuda_api_object.h cuobjdump.h; do
  cp "$SRC/libcuda/$f" "$S/libcuda/"
done
# Local patches (see README), applied in name order.
for p in "$HERE"/patches/*.patch; do
  [ -e "$p" ] || continue
  patch -s -d "$S" -p1 < "$p"
done
# Sync into $T, touching only files whose content changed (incremental make).
(cd "$S" && find . -type f) | while read -r f; do
  if ! cmp -s "$S/$f" "$T/$f"; then
    mkdir -p "$(dirname "$T/$f")"; cp "$S/$f" "$T/$f"
  fi
done
mkdir -p "$T/obj"

O="$T/obj"
C="$T/src/cuda-sim"
G="$T/gen"
rm -rf "$G"; mkdir -p "$G"
# Parsers (generated into $G, moved into $O only when they changed).
bison --name-prefix=ptx_ -d "$C/ptx.y" --file-prefix="$G/ptx" 2>/dev/null
bison --name-prefix=ptxinfo_ -d "$C/ptxinfo.y" --file-prefix="$G/ptxinfo" 2>/dev/null
flex --outfile="$G/lex.ptx_.c" "$C/ptx.l" 2>/dev/null
flex --outfile="$G/lex.ptxinfo_.c" "$C/ptxinfo.l" 2>/dev/null
# Generated headers (same recipes as upstream src/cuda-sim/Makefile).
{
  echo '// generated by difftest build.sh'
  echo '#include "ptx_ir.h"'
  echo '#ifndef instructions_h_included'
  echo '#define instructions_h_included'
  grep "_impl(" "$C/instructions.cc" | sed 's/{.*//' | sed 's/$/;/'
  echo '#endif'
} > "$G/instructions.h"
grep "=" "$G/ptx.tab.h" | sed 's/^[ ]\+//' | sed -E 's/\s+\/\*.+\*\///' \
  | sed 's/[=,]//g' | sed 's/\([_A-Z1-9]\+\)[ ]\+\([0-9]\+\)/\1 \1/' \
  | sed 's/^/DEF(/' | sed 's/ /,"/' | sed 's/$/")/' \
  | sed '/YYerror/d;/YYEOF/d;/YYEMPTY/d;/YYUNDEF/d;' > "$G/ptx_parser_decode.def"
echo "const char *g_gpgpusim_build_string=\"difftest-${COMMIT:0:12}\";" > "$G/detailed_version"
for f in "$G"/*; do
  cmp -s "$f" "$O/$(basename "$f")" || cp "$f" "$O/"
done

CXXFLAGS="-std=c++17 -O2 -w -MMD -MP -fno-strict-aliasing -DCUDART_VERSION=11000 \
 -I$HERE/stubs/include -I$O -I$C -I$T/src -I$T/libcuda"

SRCS=(
  "$C/cuda-sim.cc" "$C/cuda_device_printf.cc" "$C/cuda_device_runtime.cc"
  "$C/instructions.cc" "$C/memory.cc" "$C/ptx-stats.cc" "$C/ptx_ir.cc"
  "$C/ptx_loader.cc" "$C/ptx_parser.cc" "$C/ptx_sim.cc"
  "$O/ptx.tab.c" "$O/lex.ptx_.c" "$O/ptxinfo.tab.c" "$O/lex.ptxinfo_.c"
  "$T/src/abstract_hardware_model.cc" "$T/src/option_parser.cc"
  "$HERE/stubs/sim_stubs.cc" "$HERE/driver/gpgpusim_driver.cc"
)
# A generated Makefile, so that make -jN does the parallel compile.
MK="$O/build.mk"
{
  echo "CXX := $CXX"
  echo "CXXFLAGS := $CXXFLAGS"
  objs=""
  for s in "${SRCS[@]}"; do
    b="$(basename "$s")"; o="$O/${b%.*}.o"; objs="$objs $o"
    echo "$o: $s"
    printf '\t$(CXX) $(CXXFLAGS) -x c++ -c $< -o $@\n'
  done
  echo "-include \$(wildcard $O/*.d)"
  echo "$WORK/gpgpusim-ptx:$objs"
  printf '\t$(CXX) -o $@ $^ -lz -lpthread\n'
} > "$MK"
make -s -j"$JOBS" -f "$MK" "$WORK/gpgpusim-ptx"
echo "built $WORK/gpgpusim-ptx"
