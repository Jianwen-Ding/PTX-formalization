#!/usr/bin/env python3
"""Generate tests/atom.ptx: atom/red variants (integer, float, packed, vector, cas) against Python models."""
import struct
def f16(v): return struct.unpack('<H', struct.pack('<e', v))[0]
def f16v(b): return struct.unpack('<e', struct.pack('<H', b))[0]
def bf16(v): return struct.unpack('<I', struct.pack('<f', v))[0] >> 16
def bf16v(b): return struct.unpack('<f', struct.pack('<I', b << 16))[0]
def f32(v): return struct.unpack('<I', struct.pack('<f', v))[0]
def f32v(b): return struct.unpack('<f', struct.pack('<I', b))[0]
def f64(v): return struct.unpack('<Q', struct.pack('<d', v))[0]
def f64v(b): return struct.unpack('<d', struct.pack('<Q', b))[0]
M32, M64 = 0xFFFFFFFF, 0xFFFFFFFFFFFFFFFF
def s32(x): x &= M32; return x - (1 << 32) if x >> 31 else x
def s64(x): x &= M64; return x - (1 << 64) if x >> 63 else x
# (op line fragment, type, bytes, init, b, c, new-fn)
T = []   # (opcode-with-type, ptxty, bytes, init, b, c, expected new)
def add(op, ty, nb, init, b, new, c=None): T.append((op, ty, nb, init, b, c, new))
add("add.u32", "u32", 4, 7, 5, 12); add("add.u32", "u32", 4, M32, 2, 1)
add("add.s32", "s32", 4, (-5) & M32, 3, (-2) & M32)
add("min.u32", "u32", 4, 9, 4, 4); add("max.u32", "u32", 4, 9, 40, 40)
add("min.s32", "s32", 4, (-3) & M32, 2, (-3) & M32); add("max.s32", "s32", 4, (-3) & M32, 2, 2)
add("min.s64", "s64", 8, (-3) & M64, 2, (-3) & M64); add("max.u64", "u64", 8, 1 << 40, 5, 1 << 40)
add("and.b32", "b32", 4, 0xF0F0, 0xFF00, 0xF000); add("or.b32", "b32", 4, 0xF0F0, 0x0F0F, 0xFFFF); add("xor.b32", "b32", 4, 0xFF, 0x0F, 0xF0)
add("and.b64", "b64", 8, 0xFFFF0000FFFF, 0xFF00FF00FF00, 0xFFFF0000FFFF & 0xFF00FF00FF00)
add("inc.u32", "u32", 4, 3, 10, 4); add("inc.u32", "u32", 4, 10, 10, 0)
add("dec.u32", "u32", 4, 3, 10, 2); add("dec.u32", "u32", 4, 0, 10, 10); add("dec.u32", "u32", 4, 11, 10, 10)
add("exch.b32", "b32", 4, 111, 222, 222); add("exch.b64", "b64", 8, 1 << 50, 7, 7)
add("cas.b32", "b32", 4, 5, 5, 99, c=99); add("cas.b32", "b32", 4, 5, 6, 5, c=99)
add("cas.b64", "b64", 8, 1 << 45, 1 << 45, 3, c=3); add("cas.b16", "b16", 2, 0x1234, 0x1234, 0xABCD, c=0xABCD); add("cas.b16", "b16", 2, 0x1234, 0x1111, 0x1234, c=0xABCD)
add("add.f32", "f32", 4, f32(1.5), f32(2.25), f32(3.75)); add("add.f64", "f64", 8, f64(1.5), f64(-0.25), f64(1.25))
add("add.noftz.f16", "f16", 2, f16(1.5), f16(2.0), f16(3.5)); add("add.noftz.bf16", "bf16", 2, bf16(1.5), bf16(2.0), bf16(3.5))
add("add.noftz.f16x2", "f16x2", 4, f16(1.0) | (f16(2.0) << 16), f16(0.5) | (f16(-4.0) << 16), f16(1.5) | (f16(-2.0) << 16))
add("add.noftz.bf16x2", "bf16x2", 4, bf16(1.0) | (bf16(2.0) << 16), bf16(0.5) | (bf16(-4.0) << 16), bf16(1.5) | (bf16(-2.0) << 16))
add("min.f32", "f32", 4, f32(1.5), f32(-2.0), f32(-2.0)); add("max.f64", "f64", 8, f64(1.5), f64(2.0), f64(2.0))
add("min.f16", "f16", 2, f16(1.5), f16(-2.0), f16(-2.0)); add("max.bf16", "bf16", 2, bf16(1.5), bf16(2.0), bf16(2.0))
add("min.f16x2", "f16x2", 4, f16(1.0) | (f16(2.0) << 16), f16(0.5) | (f16(4.0) << 16), f16(0.5) | (f16(2.0) << 16))

HDR = ["// GENERATED by scripts/gen_atom.py -- atom variants vs. Python models",
       ".version 8.6\n.target sm_100\n.address_size 64\n"]
widths = {"u32": 32, "s32": 32, "b32": 32, "f32": 32, "f16x2": 32, "bf16x2": 32, "u64": 64, "s64": 64, "b64": 64, "f64": 64, "b16": 16, "f16": 16, "bf16": 16}
body = []; init = bytearray(); newmem = bytearray(); olds = []
for i, (op, ty, nb, ini, b, c, new) in enumerate(T):
    w = widths[ty]
    pad = (len(init) + nb - 1) // nb * nb
    init += bytes(pad - len(init)); newmem += bytes(pad - len(newmem))
    init += ini.to_bytes(nb, 'little'); newmem += new.to_bytes(nb, 'little'); olds.append((pad, nb, ini))
    body.append(f"    mov.b{w} %b{w}, {b};")
    cargs = ""
    if c is not None:
        body.append(f"    mov.b{w} %c{w}, {c};"); cargs = f", %c{w}"
    body.append(f"    atom.global.{op} %d{w}, [%a+{pad}], %b{w}{cargs};")
    body.append(f"    st.global.b{w} [%o+{pad}], %d{w};")
total = len(newmem)
h = lambda bs: ", ".join(str(x) for x in bs)
src = HDR[:]
src.append(".visible .entry k(.param .u64 pa, .param .u64 po)\n{\n"
           "    .reg .b64 %a, %o, %b64, %c64, %d64; .reg .b32 %b32, %c32, %d32; .reg .b16 %b16, %c16, %d16;\n"
           "    ld.param.u64 %a, [pa]; ld.param.u64 %o, [po];\n" + "\n".join(body) + "\n    ret;\n}\n")
src.append(f".buffer MEM .u8 = {{ {h(init)} }};\n.buffer OUT .u8 [{total}];\n.launch k <<< 1, 1 >>> (MEM, OUT);")
oldmem = bytearray(total)
for pad, nb, ini in olds: oldmem[pad:pad + nb] = ini.to_bytes(nb, 'little')
src.append(f".expect OUT .u8 = {{ {h(oldmem)} }};\n.expect MEM .u8 = {{ {h(newmem)} }};")
open('tests/atom.ptx', 'w').write("\n".join(src) + "\n")
print(len(T), "atomics")
