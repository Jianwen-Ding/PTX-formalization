#!/usr/bin/env python3
"""Generate tests/video.ptx: scalar and SIMD video instructions against Python
models of the ISA text (best effort; see semantics/ptx-exec-video.k).
usage: gen_video.py [N] [SEED]"""
import random, sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 16
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 8)
M32 = (1 << 32) - 1
def sx(v, w): v &= (1 << w) - 1; return v - (1 << w) if v >> (w - 1) else v
def r32(): return random.choice([0, M32, 0x80808080, 0x7F7F7F7F, 0x00FF00FF]) if random.random() < .3 else random.getrandbits(32)
def part(v, off, w, signed): x = (v >> off) & ((1 << w) - 1); return sx(x, w) if signed else x
def sat(v, w, signed):
    lo, hi = (-(1 << (w - 1)), (1 << (w - 1)) - 1) if signed else (0, (1 << w) - 1)
    return max(lo, min(hi, v))
CMP = {'eq': lambda a, b: a == b, 'ne': lambda a, b: a != b, 'lt': lambda a, b: a < b, 'le': lambda a, b: a <= b,
       'gt': lambda a, b: a > b, 'ge': lambda a, b: a >= b}
OPS = {'vadd': lambda a, b: a + b, 'vsub': lambda a, b: a - b, 'vabsdiff': lambda a, b: abs(a - b),
       'vmin': min, 'vmax': max, 'vavrg': lambda a, b: ((a + b + 1) >> 1) if a + b >= 0 else ((a + b) >> 1)}
cases = []
def case(text, ins, f): cases.append((text, ins, [f(*[c[i] for c in ins]) & M32 for i in range(N)]))
# SIMD
for nl, w in ((2, 16), (4, 8)):
    for op in ('vadd', 'vsub', 'vavrg', 'vabsdiff', 'vmin', 'vmax'):
        for s in ('u32', 's32'):
            sg = s == 's32'
            for mods in ('', '.sat', '.add'):
                A = [r32() for _ in range(N)]; B = [r32() for _ in range(N)]; X = [r32() for _ in range(N)]
                def f(a, b, c, op=op, sg=sg, mods=mods, nl=nl, w=w):
                    res = [OPS[op](part(a, i * w, w, sg), part(b, i * w, w, sg)) for i in range(nl)]
                    if '.sat' in mods: res = [sat(v, w, sg) for v in res]
                    if '.add' in mods: return c + sum(res)
                    return sum((v & ((1 << w) - 1)) << (i * w) for i, v in enumerate(res))
                case(f'{op}{nl}.{s}.{s}.{s}{mods}', [A, B, X], f)
    for cmp in ('eq', 'lt', 'ge'):
        A = [r32() for _ in range(N)]; B = [r32() for _ in range(N)]; X = [0] * N
        case(f'vset{nl}.u32.u32.{cmp}', [A, B, X],
             lambda a, b, c, cmp=cmp, nl=nl, w=w: sum(int(CMP[cmp](part(a, i * w, w, False), part(b, i * w, w, False))) << (i * w) for i in range(nl)))
# scalar
SEL = {'': (0, 32), '.b0': (0, 8), '.b1': (8, 8), '.b2': (16, 8), '.b3': (24, 8), '.h0': (0, 16), '.h1': (16, 16)}
for op in ('vadd', 'vsub', 'vabsdiff', 'vmin', 'vmax'):
    for at, bt in (('u32', 'u32'), ('s32', 's32'), ('u32', 's32')):
        for asel, bsel in (('', ''), ('.b1', '.h1'), ('.h0', '.b3')):
            for mods in ('', '.sat', '.sat.add', '.min', '.max'):
                A = [r32() for _ in range(N)]; B = [r32() for _ in range(N)]; X = [r32() for _ in range(N)]
                dt = at
                def f(a, b, c, op=op, at=at, bt=bt, asel=asel, bsel=bsel, mods=mods, dt=dt):
                    ta = part(a, *SEL[asel], at[0] == 's'); tb = part(b, *SEL[bsel], bt[0] == 's')
                    t = OPS[op](ta, tb)
                    if '.sat' in mods: t = sat(t, 32, dt[0] == 's')
                    cv = sx(c, 32) if dt[0] == 's' else c
                    if mods.endswith('.add'): t = t + cv
                    elif mods.endswith('.min'): t = min(t, cv)
                    elif mods.endswith('.max'): t = max(t, cv)
                    return t
                if random.random() < 0.35:       # keep the file small
                    sec = mods.split('.')[-1] if mods.split('.')[-1] in ('add', 'min', 'max') else ''
                    ops_txt = f'%r4{asel}, %r5{bsel}' + (', %r6' if sec else '')
                    case(f'{op}.{dt}.{at}.{bt}{mods} %r1, ' + ops_txt, [A, B, X], f)
for amod in ('clamp', 'wrap'):
    for left in ('vshl', 'vshr'):
        for s in ('u32', 's32'):
            A = [r32() for _ in range(N)]; B = [random.choice([0, 1, 8, 31, 32, 33, 100, 255]) for _ in range(N)]; X = [r32() for _ in range(N)]
            def f(a, b, c, amod=amod, left=left, s=s):
                ta = sx(a, 32) if s == 's32' else a
                n = min(b & 255, 32) if amod == 'clamp' else b & 31
                t = ta << n if left == 'vshl' else ta >> n
                return t + c
            case(f'{left}.{s}.{s}.u32.{amod}.add %r1, %r4, %r5, %r6', [A, B, X], f)
for cmp in ('eq', 'lt', 'ge'):
    A = [r32() for _ in range(N)]; B = [r32() for _ in range(N)]; X = [r32() for _ in range(N)]
    case(f'vset.u32.s32.{cmp}.add %r1, %r4.b1, %r5.h1, %r6', [A, B, X],
         lambda a, b, c, cmp=cmp: int(CMP[cmp](part(a, 8, 8, False), part(b, 16, 16, True))) + c)

PART, PARTS = (int(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) > 4 else (0, 1)
cases = cases[PART::PARTS]
print("// GENERATED by scripts/gen_video.py -- video instructions (best-effort model of the ISA text).")
print(".version 8.0\n.target sm_80\n.address_size 64\n")
for k, (text, ins, exp) in enumerate(cases):
    full = text if ' ' in text and '%r1' in text else None
    if full is None:
        full = f'{text} %r1, %r4, %r5, %r6'
    print(f".visible .entry k{k}(.param .u64 p0, .param .u64 p1, .param .u64 p2, .param .u64 po)\n{{\n    .reg .b32 %r<10>; .reg .b64 %rd<6>;\n    mov.u32 %r0, %tid.x; mul.wide.u32 %rd1, %r0, 4;")
    for j in range(3):
        print(f"    ld.param.u64 %rd2, [p{j}]; add.s64 %rd2, %rd2, %rd1; ld.global.b32 %r{4+j}, [%rd2];")
    print(f"    {full};\n    ld.param.u64 %rd3, [po]; add.s64 %rd3, %rd3, %rd1; st.global.b32 [%rd3], %r1;\n    ret;\n}}\n")
for k, (text, ins, exp) in enumerate(cases):
    for j, col in enumerate(ins): print(f".buffer I{k}_{j} .u32 = {{ {', '.join(map(str, col))} }};")
    print(f".buffer O{k} .u32 [{N}];\n.launch k{k} <<< 1, {N} >>> (I{k}_0, I{k}_1, I{k}_2, O{k});\n.expect O{k} .u32 = {{ {', '.join(map(str, exp))} }};")
