#!/usr/bin/env python3
"""Generate tests/intx.ptx: mul24/mad24, sad, dp4a/dp2a, min/max.relu and packed
16x2 integer ops against Python models.   usage: gen_intx.py [N] [SEED]"""
import random, sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 24
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 4)
M32, M64 = (1 << 32) - 1, (1 << 64) - 1
def sx(v, w): v &= (1 << w) - 1; return v - (1 << w) if v >> (w - 1) else v
def r(w):
    return random.choice([0, (1 << w) - 1, 1 << (w - 1), (1 << (w - 1)) - 1, 1, 0xFFFFFF, 0x800000]) & ((1 << w) - 1) \
        if random.random() < .3 else random.getrandbits(w)
cases = {}
def add(op, ws, rw, f):
    rows = []
    for _ in range(N):
        a = [r(w) for w in ws]
        rows.append((a, f(*a) & ((1 << rw) - 1)))
    cases[op] = (ws, rw, rows)
def v24(a, s): return sx(a, 24) if s else a & 0xFFFFFF
for s in ('u', 's'):
    sg = s == 's'
    add(f'mul24.lo.{s}32', [32, 32], 32, lambda a, b: v24(a, sg) * v24(b, sg))
    add(f'mul24.hi.{s}32', [32, 32], 32, lambda a, b: (v24(a, sg) * v24(b, sg)) >> 16)
    add(f'mad24.lo.{s}32', [32, 32, 32], 32, lambda a, b, c: v24(a, sg) * v24(b, sg) + c)
    add(f'mad24.hi.{s}32', [32, 32, 32], 32, lambda a, b, c: ((v24(a, sg) * v24(b, sg)) >> 16) + c)
def sat32(v): return max(-(1 << 31), min((1 << 31) - 1, v))
add('mad24.hi.sat.s32', [32, 32, 32], 32, lambda a, b, c: sat32(((v24(a, True) * v24(b, True)) >> 16) + sx(c, 32)))
for w in (16, 32, 64):
    for s in ('u', 's'):
        sg = s == 's'
        val = (lambda x: sx(x, w)) if sg else (lambda x: x)
        add(f'sad.{s}{w}', [w, w, w], w, lambda a, b, c, val=val: c + abs(val(a) - val(b)))
def field(v, o, w, sg): v = (v >> o) & ((1 << w) - 1); return sx(v, w) if sg else v
for sa in ('u', 's'):
    for sb in ('u', 's'):
        ga, gb = sa == 's', sb == 's'
        add(f'dp4a.{sa}32.{sb}32', [32, 32, 32], 32,
            lambda a, b, c, ga=ga, gb=gb: c + sum(field(a, 8 * i, 8, ga) * field(b, 8 * i, 8, gb) for i in range(4)))
        for mode, base in (('lo', 0), ('hi', 16)):
            add(f'dp2a.{mode}.{sa}32.{sb}32', [32, 32, 32], 32,
                lambda a, b, c, ga=ga, gb=gb, base=base: c + sum(field(a, 16 * i, 16, ga) * field(b, base + 8 * i, 8, gb) for i in range(2)))
add('min.relu.s32', [32, 32], 32, lambda a, b: max(0, min(sx(a, 32), sx(b, 32))))
add('max.relu.s32', [32, 32], 32, lambda a, b: max(0, max(sx(a, 32), sx(b, 32))))
def lanes(f, g):
    return lambda a, b: (f(a & 0xFFFF, b & 0xFFFF, g) & 0xFFFF) | ((f(a >> 16, b >> 16, g) & 0xFFFF) << 16)
for s in ('u', 's'):
    sg = s == 's'
    v = (lambda x: sx(x, 16)) if sg else (lambda x: x)
    add(f'add.{s}16x2', [32, 32], 32, lanes(lambda a, b, g: a + b, 0))
    add(f'sub.{s}16x2', [32, 32], 32, lanes(lambda a, b, g: a - b, 0))
    add(f'min.{s}16x2', [32, 32], 32, lanes(lambda a, b, g, v=v: min(v(a), v(b)), 0))
    add(f'max.{s}16x2', [32, 32], 32, lanes(lambda a, b, g, v=v: max(v(a), v(b)), 0))
    if sg:
        add('min.relu.s16x2', [32, 32], 32, lanes(lambda a, b, g, v=v: max(0, min(v(a), v(b))), 0))
        add('max.relu.s16x2', [32, 32], 32, lanes(lambda a, b, g, v=v: max(0, max(v(a), v(b))), 0))
        add('neg.s16x2', [32], 32, lambda a: ((-sx(a & 0xFFFF, 16)) & 0xFFFF) | (((-sx(a >> 16, 16)) & 0xFFFF) << 16))
        add('abs.s16x2', [32], 32, lambda a: (abs(sx(a & 0xFFFF, 16)) & 0xFFFF) | ((abs(sx(a >> 16, 16)) & 0xFFFF) << 16))

print("// GENERATED by scripts/gen_intx.py -- mul24/mad24, sad, dp4a/dp2a, relu, packed 16x2.")
print(".version 8.0\n.target sm_80\n.address_size 64\n")
out = []
for k, (op, (ws, rw, rows)) in enumerate(cases.items()):
    n = len(ws)
    ps = ", ".join(f".param .u64 p{j}" for j in range(n + 1))
    # register class per width
    cls = lambda w: {16: 'b16', 32: 'b32', 64: 'b64'}[w]
    print(f".visible .entry k{k}({ps})\n{{\n    .reg .b16 %h<8>; .reg .b32 %r<8>; .reg .b64 %rd<12>;\n    mov.u32 %r0, %tid.x;")
    regs = []
    for j, w in enumerate(ws):
        print(f"    mul.wide.u32 %rd1, %r0, {w // 8}; ld.param.u64 %rd2, [p{j}]; add.s64 %rd2, %rd2, %rd1; ld.global.{cls(w)} {'%h' if w == 16 else '%r' if w == 32 else '%rd'}{j + 4}, [%rd2];")
        regs.append(('%h' if w == 16 else '%r' if w == 32 else '%rd') + str(j + 4))
    d = {16: '%h1', 32: '%r1', 64: '%rd8'}[rw]
    print(f"    {op} {d}, {', '.join(regs)};")
    print(f"    mul.wide.u32 %rd1, %r0, {rw // 8}; ld.param.u64 %rd3, [p{n}]; add.s64 %rd3, %rd3, %rd1; st.global.{cls(rw)} [%rd3], {d};\n    ret;\n}}\n")
    out.append((k, op, ws, rw, rows))
T = {16: 'u16', 32: 'u32', 64: 'u64'}
for k, op, ws, rw, rows in out:
    for j, w in enumerate(ws):
        print(f".buffer I{k}_{j} .{T[w]} = {{ " + ", ".join(str(rw_[0][j]) for rw_ in rows) + " };")
    print(f".buffer O{k} .{T[rw]} [{len(rows)}];")
    print(f".launch k{k} <<< 1, {len(rows)} >>> (" + ", ".join([f"I{k}_{j}" for j in range(len(ws))] + [f"O{k}"]) + ");")
    print(f".expect O{k} .{T[rw]} = {{ " + ", ".join(str(r_[1]) for r_ in rows) + " };")
