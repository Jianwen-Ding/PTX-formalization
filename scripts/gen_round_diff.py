#!/usr/bin/env python3
"""Generate tests/rounding-diff-f{16,32,64}.ptx: PTX float arithmetic with every rounding
mode, .ftz and .sat, checked against the exact-rational reference
(scripts/ieee_ref.py).

usage: gen_round_diff.py [N] [SEED] [WIDTH] > tests/rounding-diff-fWIDTH.ptx
(one file per format keeps the K parser's memory use small)
"""
import random, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
import ieee_ref as R

N = int(sys.argv[1]) if len(sys.argv) > 1 else 40
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 7)
WIDTH = int(sys.argv[3]) if len(sys.argv) > 3 else 32

def rand_bits(w):
    p, emin, emax, eb = R.FMT[w]
    k = random.random()
    if k < 0.10:
        return random.choice([0, 1 << (w - 1), R.inf_bits(0, w), R.inf_bits(1, w), 1, (1 << (p - 1)) - 1,
                              1 << (p - 1), R.one_bits(w), R.one_bits(w) | (1 << (w - 1))])
    if k < 0.22:   # subnormals
        return random.getrandbits(p - 1) | (random.getrandbits(1) << (w - 1))
    if k < 0.40:   # small integers: exact results, ties
        v = random.randint(-64, 64)
        from fractions import Fraction
        if v == 0: return 0
        return R.mag_to_bits(Fraction(abs(v)), w) | ((v < 0) << (w - 1))
    if k < 0.75:   # moderate exponents
        bias = (1 << (eb - 1)) - 1
        return (random.getrandbits(1) << (w - 1)) | (random.randint(bias - 12, bias + 12) << (p - 1)) | random.getrandbits(p - 1)
    b = random.getrandbits(w)
    return b if ((b >> (p - 1)) & ((1 << eb) - 1)) != (1 << eb) - 1 else b & ~(1 << (w - 2))

ARITY = {'add': 2, 'sub': 2, 'mul': 2, 'div': 2, 'sqrt': 1, 'fma': 3}
TYPES = {16: 'f16', 32: 'f32', 64: 'f64'}
CONFIGS = []   # (w, op, modifier string)
for w, ops in ((32, ARITY), (64, ARITY), (16, ('add', 'sub', 'mul', 'fma'))):
    for op in ops:
        for m in ('rz', 'rm', 'rp'):
            CONFIGS.append((w, op, m))
for op in ('add', 'mul', 'fma', 'div', 'sqrt'):
    for m in ('rn.ftz', 'rz.ftz', 'rp.ftz', 'rn.sat', 'rm.sat', 'rz.ftz.sat'):
        CONFIGS.append((32, op, m))
for op in ('add', 'fma'):
    for m in ('rn.ftz', 'rm.ftz', 'rn.sat'):
        CONFIGS.append((16, op, m))

CONFIGS = [c for c in CONFIGS if c[0] == WIDTH]
inputs = {w: [[rand_bits(w) for _ in range(N)] for _ in range(3)] for w in (16, 32, 64)}
# a few subnormal-boundary cases where ftz matters
inputs[32][0][0:3] = [0x00800000, 0x007FFFFF, 0x80800000]
inputs[32][1][0:3] = [0x3F000000, 0x3F800000, 0x3F000001]

def ptype(w): return {16: 'u16', 32: 'u32', 64: 'u64'}[w]
def rtype(w): return {16: 'b16', 32: 'f32', 64: 'f64'}[w]
def rg(w): return {16: '%h', 32: '%f', 64: '%fd'}[w]

print("// GENERATED by scripts/gen_round_diff.py -- rounding modes, .ftz and .sat")
print("// checked against the exact-rational reference scripts/ieee_ref.py.")
print(".version 8.0\n.target sm_80\n.address_size 64\n")
kernels, launches, expects, bufs = [], [], [], []
for ci, (w, op, mods) in enumerate(CONFIGS):
    n_in = ARITY[op]
    mode = mods.split('.')[0]
    ftz = 'ftz' in mods
    sat = 'sat' in mods
    ins = [inputs[w][i] for i in range(n_in)]
    outs = []
    for i in range(N):
        args = [ins[j][i] for j in range(n_in)]
        r = R.ref(op, args, mode, w, ftz, sat)
        outs.append(r)
    if sat:   # the sign of a zero result under .sat is not asserted
        keep = [i for i in range(N) if R.classify(outs[i], w)[0] != 'zero']
    else:
        keep = list(range(N))
    name = f"k{ci}"
    r = rg(w); t = rtype(w); sz = w // 8
    body = []
    for j in range(n_in):
        body.append(f"    ld.param.u64 %rd1, [p{j}]; add.s64 %rd1, %rd1, %rd0; ld.global.{t} {r}{j+1}, [%rd1];")
    body.append(f"    {op}.{mods}.{TYPES[w]} {r}9, " + ", ".join(f"{r}{j+1}" for j in range(n_in)) + ";")
    body.append(f"    ld.param.u64 %rd2, [p{n_in}]; add.s64 %rd2, %rd2, %rd0; st.global.{t} [%rd2], {r}9;")
    ps = ",\n    ".join(f".param .u64 p{i}" for i in range(n_in + 1))
    print(f".visible .entry {name}(\n    {ps})\n{{")
    print("    .reg .b32 %r<2>;\n    .reg .b16 %h<10>;\n    .reg .f32 %f<10>;\n    .reg .f64 %fd<10>;\n    .reg .b64 %rd<4>;")
    print("    mov.u32 %r1, %tid.x;")
    print(f"    mul.wide.u32 %rd0, %r1, {sz};")
    print("\n".join(body))
    print("    ret;\n}\n")
    launches.append((name, w, n_in, outs, keep, op, mods, ins))
for w in (WIDTH,):
    for j in range(3):
        print(f".buffer I{w}_{j} .{ptype(w)} = {{ " + ", ".join(str(v) for v in inputs[w][j]) + " };")
for name, w, n_in, outs, keep, op, mods, ins in launches:
    if len(keep) == N:
        srcs = [f"I{w}_{j}" for j in range(n_in)]
    else:   # private inputs holding only the vectors whose result is not a zero
        srcs = [f"J_{name}_{j}" for j in range(n_in)]
        for j in range(n_in):
            print(f".buffer {srcs[j]} .{ptype(w)} = {{ " + ", ".join(str(ins[j][i]) for i in keep) + " };")
    cnt = len(keep)
    print(f".buffer O_{name} .{ptype(w)} [{cnt}];")
    print(f".launch {name} <<< 1, {cnt} >>> ({', '.join(srcs + ['O_' + name])});")
    print(f".expect O_{name} .{ptype(w)} = {{ " + ", ".join(str(outs[i]) for i in keep) + " };")
