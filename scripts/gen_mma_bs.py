#!/usr/bin/env python3
"""Generate tests/mma-bs-*.ptx: mma.sync kind::f8f6f4 (fp6 / fp4 in 8-bit containers) and kind::mxf8f6f4 / mxf4 / mxf4nvf4 .block_scale
against an exact model (fragment layouts from gen_mma.py's independent transcription).  usage: gen_mma_bs.py"""
import random, sys, io, contextlib
from fractions import Fraction
here = __file__.rsplit('/', 1)[0]
sys.path.insert(0, here)
src = open(here + '/gen_mma.py').read().split('cases = []')[0]
sys.argv = [sys.argv[0]]
exec(compile(src, 'gen_mma_prefix', 'exec'))
random.seed(41)
def mini_tab2(e, m):
    bias = (1 << (e - 1)) - 1; t = {}
    for c in range(1 << (e + m + 1)):
        s, E, M = c >> (e + m), (c >> m) & ((1 << e) - 1), c & ((1 << m) - 1)
        v = Fraction(M, 1 << m) * Fraction(2) ** (1 - bias) if E == 0 else Fraction((1 << m) + M, 1 << m) * Fraction(2) ** (E - bias)
        t[c] = -v if s else v
    return t
MINI.update({'e2m3': mini_tab2(2, 3), 'e3m2': mini_tab2(3, 2), 'e2m1': mini_tab2(2, 1)})
def ue8m0(x): return Fraction(2) ** (x - 127)
def ue4m3(x):
    e, m = x >> 3, x & 7
    return Fraction(m, 8) * Fraction(2) ** (1 - 7) if e == 0 else Fraction(8 + m, 8) * Fraction(2) ** (e - 7)
def code(ty):               # element code
    return random.choice(list(MINI[ty])) if ty in ('e2m3', 'e3m2', 'e2m1') else rand_float_bits(ty)
def container(ty, c):       # 8-bit container with random padding (ISA: e2m1 in the central 4 bits, fp6 in the low 6 bits)
    if ty == 'e2m1': return (random.getrandbits(2) << 6) | (c << 2) | random.getrandbits(2)
    if ty in ('e2m3', 'e3m2'): return (random.getrandbits(2) << 6) | c
    return c
# (shape, kind, scale_vec qualifier ('' = default), dtype, atype, btype, stype, byte-id-a, thread-id-a, byte-id-b, thread-id-b)
CFG = [('m16n8k32', 'kind::f8f6f4', None, 'f32', 'e3m2', 'e2m3', None, 0, 0, 0, 0),
       ('m16n8k32', 'kind::f8f6f4', None, 'f16', 'e2m1', 'e4m3', None, 0, 0, 0, 0),
       ('m16n8k32', 'kind::f8f6f4', None, 'f32', 'e5m2', 'e2m1', None, 0, 0, 0, 0),
       ('m16n8k32', 'kind::mxf8f6f4', '.scale_vec::1X', 'f32', 'e4m3', 'e2m3', 'ue8m0', 2, 1, 3, 2),
       ('m16n8k32', 'kind::mxf8f6f4', '', 'f32', 'e2m1', 'e5m2', 'ue8m0', 0, 0, 1, 1),
       ('m16n8k64', 'kind::mxf4', '', 'f32', 'e2m1', 'e2m1', 'ue8m0', 2, 1, 0, 3),
       ('m16n8k64', 'kind::mxf4', '.scale_vec::2X', 'f32', 'e2m1', 'e2m1', 'ue8m0', 0, 0, 2, 0),
       ('m16n8k64', 'kind::mxf4nvf4', '.scale_vec::4X', 'f32', 'e2m1', 'e2m1', 'ue4m3', 0, 1, 0, 2),
       ('m16n8k64', 'kind::mxf4nvf4', '.scale_vec::2X', 'f32', 'e2m1', 'e2m1', 'ue8m0', 2, 0, 0, 1),
       ('m16n8k64', 'kind::mxf4nvf4', '.scale_vec::4X', 'f32', 'e2m1', 'e2m1', 'ue8m0', 0, 0, 0, 0)]
def gen(kk, row):
    shape, kind, sv, dt, at, bt, st, bida, tida, bidb, tidb = row
    print("// GENERATED by scripts/gen_mma_bs.py -- mma.sync kind::f8f6f4 / block-scaled kinds vs. an exact model.")
    print(".version 8.7\n.target sm_120a\n.address_size 64\n")
    m, n, k = [int(x) for x in shape[1:].replace('n', ' ').replace('k', ' ').split()]
    packed4 = kind in ('kind::mxf4', 'kind::mxf4nvf4')
    ew = 4 if packed4 else 8
    ct = dt
    LA, LB, LC = check_bij('A', shape, ew), check_bij('B', shape, ew), check_bij('C', shape, 16 if dt == 'f16' else 32)
    A = {p: code(at) for p in LA.values()}; B = {p: code(bt) for p in LB.values()}
    C = {p: rand_float_bits(ct) for p in LC.values()}
    nsc = 1 if st is None else (int(sv[-2]) if sv else (2 if kind == 'kind::mxf4' else 1))
    dec = ue4m3 if st == 'ue4m3' else ue8m0
    rnd_s = (lambda: random.randint(0x30, 0x48)) if st == 'ue4m3' else (lambda: random.randint(122, 131))
    SA = [[rnd_s() for _ in range(nsc)] for _ in range(m)]; SB = [[rnd_s() for _ in range(nsc)] for _ in range(n)]
    D = {}
    blk = k // nsc
    for r in range(m):
        for c in range(n):
            s = fval(ct, C[(r, c)])
            for k2 in range(k):
                p = fval(at, A[(r, k2)]) * fval(bt, B[(k2, c)])
                if st is not None: p *= dec(SA[r][k2 // blk]) * dec(SB[c][k2 // blk])
                s += p
            D[(r, c)] = to_bits(dt, s)
    vals = lambda M_, ty: {p: (v if packed4 else container(ty, v)) for p, v in M_.items()}
    fa = frag_regs(LA, vals(A, at), ew, m * k // 32, 32); fb = frag_regs(LB, vals(B, bt), ew, k * n // 32, 32)
    fc = frag_regs(LC, C, 16 if ct == 'f16' else 32, m * n // 32, 32); fd = frag_regs(LC, D, 16 if dt == 'f16' else 32, m * n // 32, 32)
    na, nb_, nc, nd = len(fa[0]), len(fb[0]), len(fc[0]), len(fd[0])
    wsa = [random.getrandbits(32) for _ in range(32)]; wsb = [random.getrandbits(32) for _ in range(32)]
    if st is not None:                     # lanes that supply scale factors; all others hold garbage
        for r in range(m):
            lane = (r % 8) * 4 + 2 * tida + r // 8
            for j in range(nsc):
                sh = 8 * (bida + j); wsa[lane] = (wsa[lane] & ~(255 << sh)) | (SA[r][j] << sh)
        for c in range(n):
            lane = c * 4 + tidb
            for j in range(nsc):
                sh = 8 * (bidb + j); wsb[lane] = (wsb[lane] & ~(255 << sh)) | (SB[c][j] << sh)
    rg = lambda pre, i: f"%{pre.upper()}{i}"
    vec = lambda nm, n_: "{" + ", ".join(rg(nm, i) for i in range(n_)) + "}"
    print(f".visible .entry k{kk}(.param .u64 pa, .param .u64 pb, .param .u64 pc, .param .u64 ps, .param .u64 po)\n{{\n    .reg .b32 %r<8>, %SA, %SB; .reg .b32 %A<{na}>, %B<{nb_}>, %C<{nc}>, %D<{nd}>; .reg .b64 %rd<4>;")
    print("    mov.u32 %r0, %tid.x;")
    for nm, nreg, par in (('a', na, 'pa'), ('b', nb_, 'pb'), ('c', nc, 'pc')):
        print(f"    ld.param.u64 %rd0, [{par}]; mul.wide.u32 %rd1, %r0, {nreg * 4}; add.s64 %rd0, %rd0, %rd1;")
        for i in range(nreg): print(f"    ld.global.b32 {rg(nm, i)}, [%rd0+{i * 4}];")
    print("    ld.param.u64 %rd0, [ps]; mul.wide.u32 %rd1, %r0, 4; add.s64 %rd0, %rd0, %rd1;\n    ld.global.b32 %SA, [%rd0];\n    ld.global.b32 %SB, [%rd0+128];")
    if st is None:
        print(f"    mma.sync.aligned.{shape}.row.col.{kind}.{dt}.{at}.{bt}.{ct} {vec('d', nd)}, {vec('a', na)}, {vec('b', nb_)}, {vec('c', nc)};")
    else:
        print(f"    mma.sync.aligned.{shape}.row.col.{kind}.block_scale{sv}.f32.{at}.{bt}.f32.{st} {vec('d', nd)}, {vec('a', na)}, {vec('b', nb_)}, {vec('c', nc)}, %SA, {{{bida}, {tida}}}, %SB, {{{bidb}, {tidb}}};")
    print(f"    ld.param.u64 %rd0, [po]; mul.wide.u32 %rd1, %r0, {nd * 4}; add.s64 %rd0, %rd0, %rd1;")
    for i in range(nd): print(f"    st.global.b32 [%rd0+{i * 4}], {rg('d', i)};")
    print("    ret;\n}\n")
    flat = lambda f: ", ".join(str(x) for lane in f for x in lane)
    print(f".buffer A{kk} .u32 = {{ {flat(fa)} }};\n.buffer B{kk} .u32 = {{ {flat(fb)} }};\n.buffer C{kk} .u32 = {{ {flat(fc)} }};\n"
          f".buffer S{kk} .u32 = {{ {', '.join(str(x) for x in wsa + wsb)} }};\n"
          f".buffer O{kk} .u32 [{32 * nd}];\n.launch k{kk} <<< 1, 32 >>> (A{kk}, B{kk}, C{kk}, S{kk}, O{kk});\n.expect O{kk} .u32 = {{ {flat(fd)} }};")
for kk, row in enumerate(CFG):
    sio = io.StringIO()
    with contextlib.redirect_stdout(sio): gen(kk, row)
    open(f'tests/mma-bs-{kk}.ptx', 'w').write(sio.getvalue())
print(len(CFG), "tests")
