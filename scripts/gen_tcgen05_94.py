#!/usr/bin/env python3
"""Generate tests/tc-94-*.ptx (and a few tests/neg variants): the PTX ISA 9.4 tcgen05.mma additions against exact models.
  - .kind::ti16 (9.7.18.4.2 Table 53): A / B .s1z4m11 in [-2047, 2047] (read as 16-bit two's complement), D .s32, K = 16
    dense / 32 sparse, integer negation, the .s32 sum wrapped (no saturation); dense (A in shared or tensor memory, B
    K- or MN-major), sparse (2:4, metadata in the .kind::f16 layout of Figures 287 / 288, sparsity selector) and .ws.
  - UE5M3 scale type (Table 55 bits 23-24 = 2) for .kind::mxf4nvf4: 5 exponent bits (bias 15), 3 mantissa bits.
  - .decompress::lut::b (9.7.18.10.8, 9.7.18.4.1): per N row a K = 128 block of 3-bit indices (48 bytes, LSB first) of
    which descriptor bit 53 selects the first / second 24 bytes (K = 64); the 8-byte table of N slice n / 8 in TMEM lane
    n / 8, two columns from b-decompress-metadata (entry j: column + j / 4, byte j % 4).
  - .collector qualifiers (no effect on the result; a fill before a use under .ub strict).
usage: gen_tcgen05_94.py"""
import random, sys
from fractions import Fraction
here = __file__.rsplit('/', 1)[0]
s = open(here + '/gen_tcgen05_x.py').read()
exec(compile(s[:s.index('def zmask')], 'gen_x_prefix', 'exec'))
random.seed(94)
HDR94 = "// GENERATED by scripts/gen_tcgen05_94.py\n"

def ue8m0(x): return Fraction(2) ** (x - 127)
def ue5m3(x):                                   # 5.2.3: unsigned, 5 exponent bits, 3 mantissa bits; 0xff NaN (not used)
    assert x != 0xFF
    e, m = x >> 3, x & 7
    return Fraction(m, 8) * Fraction(2) ** (1 - 15) if e == 0 else Fraction(8 + m, 8) * Fraction(2) ** (e - 15)
def ti16(): return random.choice([-2047, 2047, 0, 1, -1]) if random.random() < .15 else random.randint(-2047, 2047)
def s32(x): x &= 0xFFFFFFFF; return x - (1 << 32) if x >> 31 else x
NIBS = [0b0100, 0b1000, 0b1100, 0b1001, 0b1101, 0b0110, 0b1110]   # 9.7.18.10.9.2 meaningful 2:4 index values
E4M3 = [c for c in MINI['e4m3'] if (c & 0x7F) != 0x7F]

def image(img):
    size = (max(img) + 1 + 2047) // 2048 * 2048
    return size, bytes(img.get(i, 0) for i in range(size))

def patches(data):
    out = f"\n.buffer IMG .u8 [{len(data)}];\n"
    i = 0
    while i < len(data):
        if data[i] == 0: i += 1; continue
        j = i
        while j < len(data) and (j - i < 400) and not (data[j] == 0 and all(x == 0 for x in data[j:j + 16])): j += 1
        out += f".patch IMG .u8 @ {i} = {{ {h(data[i:j])} }};\n"
        i = j
    return out

def program(kk, data, nd, din, dout, dty, extra, setup, mmas, directives='', target='sm_107f', first=''):
    """one kernel: shared image, D (nd columns of lanes 0..127), extra TMEM tables [(column, ncols, words[128][ncols])],
    the register setup lines and the mma lines (issued by thread 0), D read back"""
    size = len(data)
    L = [first + HDR94 + f".version 9.4\n.target {target}\n.address_size 64\n" + directives]
    np_ = len(extra)
    params = ", ".join(["pimg", "pd"] + [f"px{i}" for i in range(np_)] + ["po"])
    L.append(f""".visible .entry k{kk}({", ".join(".param .u64 " + p for p in params.split(", "))})
{{
    .reg .b32 %r<10>, %x<4>, %D<{nd}>, %X<8>; .reg .b64 %rd<8>; .reg .b64 %dA, %dB; .reg .b32 %idesc, %tl, %tw;
    .reg .pred %p, %q;
    .shared .align 1024 .b8 buf[{size}];
    .shared .align 16 .b32 slot[2];
    mov.u32 %tl, %tid.x;
    mov.u32 %r3, 0; mov.u32 %r4, 0;
    mov.u64 %rd5, slot;
    setp.lt.u32 %p, %tl, 32;
    setp.eq.u32 %q, %tl, 0;
    @%p tcgen05.alloc.cta_group::1.sync.aligned.shared::cta.b32 [%rd5], 512;
    ld.param.u64 %rd0, [pimg]; mov.u64 %rd2, buf; mul.wide.u32 %rd1, %tl, 16; add.u64 %rd0, %rd0, %rd1; add.u64 %rd2, %rd2, %rd1;""")
    for it in range(size // 2048):
        o = it * 2048
        L.append(f"    ld.global.b32 %x0, [%rd0+{o}]; ld.global.b32 %x1, [%rd0+{o + 4}]; ld.global.b32 %x2, [%rd0+{o + 8}]; ld.global.b32 %x3, [%rd0+{o + 12}];")
        L.append(f"    st.shared.b32 [%rd2+{o}], %x0; st.shared.b32 [%rd2+{o + 4}], %x1; st.shared.b32 [%rd2+{o + 8}], %x2; st.shared.b32 [%rd2+{o + 12}], %x3;")
    L.append("    bar.sync 0;\n    shr.u32 %tw, %tl, 5; shl.b32 %tw, %tw, 21;")
    L.append(f"    ld.param.u64 %rd0, [pd]; mul.wide.u32 %rd1, %tl, {nd * 4}; add.u64 %rd0, %rd0, %rd1;")
    for i in range(nd): L.append(f"    ld.global.b32 %D{i}, [%rd0+{i * 4}];")
    L.append(f"    tcgen05.st.sync.aligned.32x32b.x{nd}.b32 [%tw], {vec('D', nd)};")
    for i, (col, nc, _) in enumerate(extra):
        L.append(f"    ld.param.u64 %rd0, [px{i}]; mul.wide.u32 %rd1, %tl, {4 * nc}; add.u64 %rd0, %rd0, %rd1;")
        for j in range(nc): L.append(f"    ld.global.b32 %X{j}, [%rd0+{4 * j}];")
        L.append(f"    add.u32 %r1, %tw, {col};\n    tcgen05.st.sync.aligned.32x32b.x{nc}.b32 [%r1], {vec('X', nc)};")
    L.append("    tcgen05.wait::st.sync.aligned;\n    tcgen05.fence::before_thread_sync;\n    bar.sync 0;")
    L += ["    " + x for x in setup]
    L.append("    mov.b32 %r5, 0;")
    L += ["    @%q " + x for x in mmas]
    L.append("    tcgen05.fence::after_thread_sync;\n    bar.sync 0;")
    L.append(f"    tcgen05.ld.sync.aligned.32x32b.x{nd}.b32 {vec('D', nd)}, [%tw];\n    tcgen05.wait::ld.sync.aligned;")
    L.append(f"    ld.param.u64 %rd0, [po]; mul.wide.u32 %rd1, %tl, {nd * 4}; add.u64 %rd0, %rd0, %rd1;")
    for i in range(nd): L.append(f"    st.global.b32 [%rd0+{i * 4}], %D{i};")
    L.append("    bar.sync 0;\n    @%p tcgen05.dealloc.cta_group::1.sync.aligned.b32 %r4, 512;\n    ret;\n}\n")
    code = "\n".join(L) + patches(data)
    code += buf('DIN', dty, din) + "\n"
    for i, (_, _, words) in enumerate(extra): code += buf(f'X{i}', 'u32', [w for row in words for w in row]) + "\n"
    code += f".buffer O .{dty} [{128 * nd}];\n.launch k{kk} <<< 1, 128 >>> ({', '.join(['IMG', 'DIN'] + [f'X{i}' for i in range(np_)] + ['O'])});\n"
    if dout is not None: code += expect('O', dty, dout) + "\n"
    return code

def flat(rows): return [x for r in rows for x in r]

# ---------------------------------------------------------------- .kind::ti16
def ti16_case(kk, M, N, sparse, aform, az, bkm, bz, negA, negB, en, sel, ws, quals, twice=False, bad=None, path=None,
              first='', directives='', idesc_or=0):
    K = 32 if sparse else 16
    A = [[ti16() for _ in range(K)] for _ in range(M)]
    nib = {}
    packed = [[] for _ in range(M)]
    if sparse:
        for r in range(M):
            for c in range(K // 4):
                v = random.choice(NIBS); nib[(r, c)] = v
                vals = [ti16() for _ in range(2)]
                for j in range(4): A[r][4 * c + j] = 0
                for j in range(2): A[r][4 * c + ((v >> (2 * j)) & 3)] = vals[j]     # packed element j at position nib[2j+1:2j]
                packed[r] += vals
    else:
        packed = [row[:] for row in A]
    if bad: packed[bad[0]][bad[1]] = 2048
    B = [[ti16() for _ in range(K)] for _ in range(N)]
    Din = [[random.choice([0, 1, 0x7FFFFFF0, 0x80000005, 0xFFFFFFFF, random.getrandbits(32)]) for _ in range(N)] for _ in range(M)]
    sa, sb = (-1 if negA else 1), (-1 if negB else 1)
    Dout = [[(s32(Din[r][c]) * en + (2 if twice else 1) * sum(sa * A[r][k] * sb * B[c][k] for k in range(K))) & 0xFFFFFFFF
             for c in range(N)] for r in range(M)]
    kp = len(packed[0])
    img = {}; off = 0; descA = 0
    u16 = lambda rows: [[x & 0xFFFF for x in row] for row in rows]
    if aform == 'desc':
        a_img, la, sa_ = build_tile(u16(packed), M, kp, 16, True, az, 0)
        img.update(a_img); descA = desc100(0, la, sa_, az); off = (max(a_img) + 1 + 1023) // 1024 * 1024
    b_img, lb, sb_ = build_tile(u16(B), N, K, 16, bkm, bz, off)
    img.update(b_img); descB = desc100(off, lb, sb_, bz)
    size, data = image(img)
    idesc = (sel & 3) | ((1 if sparse else 0) << 2) | (2 << 4) | (3 << 7) | (3 << 10) | (negA << 13) | (negB << 14) \
          | ((0 if bkm else 1) << 16) | ((N >> 3) << 17) | ((M >> 4) << 24) | idesc_or
    extra = []
    AC, MC = 256, 384
    if aform == 'tmem':
        aw = [[(packed[r][2 * w] & 0xFFFF) | ((packed[r][2 * w + 1] & 0xFFFF) << 16) for w in range(kp // 2)] if r < M else [0] * (kp // 2)
              for r in range(128)]
        extra.append((AC, kp // 2, aw))
    if sparse:
        # Figures 287 / 288 (.kind::f16 / .kind::ti16): in each block of 16 rows (lanes 16b..16b+15), lane 16b + 8hf + i holds
        # chunks 4hf..4hf+3 of rows 16b + i (bits 0-15) and 16b + i + 8 (bits 16-31), in the column of the sparsity selector
        mw = []
        for l in range(128):
            row = [random.getrandbits(32) for _ in range(4)]
            if l < M:
                b, hf, i = l // 16, (l % 16) // 8, l % 8
                row[sel] = sum(nib[(16 * b + i + 8 * hh, 4 * hf + cc)] << (16 * hh + 4 * cc) for hh in range(2) for cc in range(4))
            mw.append(row)
        extra.append((MC, 4, mw))
    a_op = '%dA' if aform == 'desc' else f'[%r2]'
    setup = [f"mov.b64 %dB, {descB};", f"mov.b32 %idesc, {idesc};", f"mov.b64 %dA, {descA};", f"mov.u32 %r2, {AC};", f"mov.u32 %r6, {MC};"]
    if ws:
        mmas = [f"tcgen05.mma.ws.cta_group::1.kind::ti16{quals[0]} [%r3], {a_op}, %dB, %idesc, {en};"]
    elif sparse:
        mmas = [f"tcgen05.mma.sp.cta_group::1.kind::ti16{quals[0]} [%r3], {a_op}, %dB, [%r6], %idesc, {{%r5, %r5, %r5, %r5}}, {en};"]
    else:
        mmas = [f"tcgen05.mma.cta_group::1.kind::ti16{q} [%r3], {a_op}, %dB, %idesc, {{%r5, %r5, %r5, %r5}}, {en if i == 0 else 1};"
                for i, q in enumerate(quals)]
    din = flat([[Din[u][c] if u < M else 0 for c in range(N)] for u in range(128)])
    dout = flat([[Dout[u][c] if u < M else 0 for c in range(N)] for u in range(128)])
    code = program(kk, data, N, din, None if path else dout, 'u32', extra, setup, mmas, directives, first=first)
    open(path or f'tests/tc-94-{kk}.ptx', 'w').write(code)

