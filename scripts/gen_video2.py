#!/usr/bin/env python3
"""tests/video-6.ptx: SIMD selectors / masks / merge with c, and scalar data merge (d.dsel), from the ISA semantics."""
import random
random.seed(11)
M32 = 0xffffffff
def sx(v, w): return v - (1 << w) if v >> (w - 1) & 1 else v
def elems(a, b, w):   # list of unsigned elements of concat(a,b)
    n = 32 // w
    return [(a >> (w * i)) & ((1 << w) - 1) for i in range(n)] + [(b >> (w * i)) & ((1 << w) - 1) for i in range(n)]
def simd(op, signed, sat, a, b, c, asel, bsel, mask, add, n):
    w = 32 // n
    E = elems(a, b, w)
    def pick(sel, i):
        k = int(sel[1:][n - 1 - i]); v = E[k]; return sx(v, w) if signed else v
    t = []
    for i in range(n):
        x, y = pick(asel, i), pick(bsel, i)
        v = {'vadd': x + y, 'vsub': x - y, 'vavrg': ((x + y + 1) >> 1) if x + y >= 0 else ((x + y) >> 1),
             'vabsdiff': abs(x - y), 'vmin': min(x, y), 'vmax': max(x, y)}[op]
        if sat:
            lo, hi = (-(1 << (w - 1)), (1 << (w - 1)) - 1) if signed else (0, (1 << w) - 1)
            v = max(lo, min(hi, v))
        t.append(v)
    has = lambda i: str(i) in mask[1:]
    if add:
        d = c
        for i in range(n):
            if has(i): d += t[i]
        return d & M32
    d = 0
    for i in range(n):
        d |= ((t[i] if has(i) else (c >> (w * i))) & ((1 << w) - 1)) << (w * i)
    return d & M32
cases = []   # (ptx line pattern, expected)
vals = [(0x8001_7ff0, 0x0003_fffe, 0xaaaa_bbbb), (0x1234_5678, 0x9abc_def0, 0x0f0f_f0f0)]
out = []; lines = []
def add_case(line, exp):
    lines.append(line); out.append(exp)
for (a, b, c) in vals:
    pre = f'    mov.u32 %a, {a}; mov.u32 %b, {b}; mov.u32 %c, {c};'
    lines.append(pre)
    for op in ['vadd', 'vsub', 'vavrg', 'vabsdiff', 'vmin', 'vmax']:
        for sg, T in ((True, 's32'), (False, 'u32')):
            # 2-way with explicit selectors and masks
            for (asel, bsel, mask, add, sat) in [('h10', 'h32', 'h10', False, False), ('h01', 'h23', 'h0', False, True), ('h33', 'h00', 'h1', False, False),
                                                 ('h21', 'h30', 'h10', True, False)]:
                dd = f'{op}2.{T}.{T}.{T}' + ('.sat' if sat else '') + ('.add' if add else '')
                lines.append(f'    {dd} %d, %a.{asel}, %b.{bsel}, %c;') if False else None
                lines.append(f'    mov.u32 %d, 0; {dd} %d.{mask}, %a.{asel}, %b.{bsel}, %c; st.global.u32 [%o+{4*len(out)}], %d;')
                out.append(simd(op, sg, sat, a, b, c, asel, bsel, mask, add, 2))
            for (asel, bsel, mask, add, sat) in [('b3210', 'b7654', 'b3210', False, False), ('b0123', 'b4567', 'b21', False, True),
                                                 ('b5555', 'b1111', 'b30', False, False), ('b6420', 'b7531', 'b3210', True, False)]:
                dd = f'{op}4.{T}.{T}.{T}' + ('.sat' if sat else '') + ('.add' if add else '')
                lines.append(f'    mov.u32 %d, 0; {dd} %d.{mask}, %a.{asel}, %b.{bsel}, %c; st.global.u32 [%o+{4*len(out)}], %d;')
                out.append(simd(op, sg, sat, a, b, c, asel, bsel, mask, add, 4))
# scalar merge: vadd.u32.u32.u32 d.b2, a, b, c  -> bits [23:16] of c replaced by (a+b)&0xff (sat to u8 with .sat)
for sat in (False, True):
    for dsel, w, pos in (('b2', 8, 16), ('h1', 16, 16), ('b0', 8, 0)):
        a, b, c = 200, 100, 0x11223344
        v = a + b
        if sat: v = min(v, (1 << w) - 1)
        exp = (c & ~(((1 << w) - 1) << pos) & M32) | ((v & ((1 << w) - 1)) << pos)
        lines.append(f'    mov.u32 %a, {a}; mov.u32 %b, {b}; mov.u32 %c, {c}; vadd.u32.u32.u32{".sat" if sat else ""} %d.{dsel}, %a, %b, %c; st.global.u32 [%o+{4*len(out)}], %d;')
