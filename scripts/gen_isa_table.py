#!/usr/bin/env python3
"""Generate semantics/ptx-isa-table.k: minimum PTX ISA version and target (sm_NN, optionally arch-specific
`a`/`f` suffix) per instruction, mined from the "PTX ISA Notes" / "Target ISA Notes" of the
PTX ISA HTML document (text rendering).  Heuristic: an opcode that appears in several sections (add for f32 and
for f16, ...) gets the minimum over the sections, qualifier-level notes are not used (too noisy).
usage: gen_isa_table.py ptx-isa.txt > semantics/ptx-isa-table.k"""
import re, sys
t = open(sys.argv[1], errors='ignore').read().split('\n')
hdr = re.compile(r'^ (9\.7\.\d+(?:\.\d+)*)\. (.+?)\s*$')
idx = [(i, m.group(1), m.group(2).replace('', '').strip()) for i, l in enumerate(t) if i > 7000 and (m := hdr.match(l))]
def vnum(s): a, b = s.split('.'); return int(a) * 10 + int(b)
def smnum(s):
    m = re.match(r'sm_(\d+)([af]?)', s); return int(m.group(1)), m.group(2)
base = {}      # op -> [ver, sm, archflag]
qual = {}      # (op, qualifier) -> [ver, sm]
def upd(d, k, ver, sm, arch):
    cur = d.get(k)
    if cur is None: d[k] = [ver, sm, arch]; return
    cur[0] = min(cur[0], ver); cur[1] = min(cur[1], sm); cur[2] = cur[2] and arch
for k, (i, num, title) in enumerate(idx):
    end = idx[k + 1][0] if k + 1 < len(idx) else len(t)
    body = t[i + 1:end]
    if not any('PTX ISA Notes' in b for b in body): continue
    try:
        a = next(j for j, b in enumerate(body) if b.strip() == 'Syntax'); d = next(j for j, b in enumerate(body) if b.strip() == 'Description')
    except StopIteration: continue
    ops = set()
    for b in body[a + 1:d]:
        m = re.match(r'^\s*(?:@\w+\s+)?([a-z][a-z0-9_]*)[\s.;{]', b)
        if m and not b.lstrip().startswith('.'): ops.add(m.group(1))
    if not ops: continue
    txt = ' '.join(x.strip() for x in body[d:])
    notes = txt[txt.find('PTX ISA Notes'):] if 'PTX ISA Notes' in txt else ''
    ex = notes.find('Examples'); notes = notes[:ex] if ex > 0 else notes
    ver = re.findall(r'Introduced in PTX ISA version (\d+\.\d+)', notes)
    v0 = vnum(ver[0]) if ver else 10
    sms = re.findall(r'Requires (sm_\d+[af]?) or higher', notes)
    listed = re.findall(r'\b(sm_\d+[af]?)\b', notes.split('Target ISA Notes')[-1][:600]) if 'Target ISA Notes' in notes else []
    if sms: s0, arch = smnum(sms[0]); arch = arch != ''
    elif listed:
        nums = [smnum(x) for x in listed]; s0 = min(n for n, _ in nums); arch = all(a != '' for _, a in nums)
    else: s0, arch = 0, False
    for op in ops: upd(base, op, v0, s0, arch)
out = ['// GENERATED by scripts/gen_isa_table.py from the PTX ISA document -- do not edit.',
       '// isaRows(op) lists rows isaRow(qualifier, min PTX version x10, min sm, arch-specific?); ',
       'requires "ptx-common.k"', '', 'module PTX-ISA-TABLE', '  imports PTX-COMMON', '',
       '  syntax IsaRow ::= isaRow(String, Int, Int, Bool)',
       '  syntax List ::= isaRows(String) [function, total]']
for op in sorted(base):
    v, s, a = base[op]
    out.append(f'  rule isaRows("{op}") => ListItem(isaRow("", {v}, {s}, {"true" if a else "false"}))')
out.append('  rule isaRows(_) => .List [owise]')
out.append('endmodule')
print('\n'.join(out))
