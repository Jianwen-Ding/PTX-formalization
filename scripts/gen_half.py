#!/usr/bin/env python3
"""Generate tests/half-*.ptx: packed f16x2/bf16x2 and scalar f16/bf16 min/max/neg/abs/relu/set/setp
against the exact-rational reference.   usage: gen_half.py [N] [SEED] [PART PARTS]"""
import random, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
import ieee_ref as R
N = int(sys.argv[1]) if len(sys.argv) > 1 else 16
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 21)
PART, PARTS = (int(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) > 4 else (0, 1)
FM = {'f16': 16, 'bf16': 116}
def rnd(w):
    p, emin, emax, eb = R.FMT[w]; cw = R.CW[w]; bias = (1 << (eb - 1)) - 1
    k = random.random()
    if k < .15: return random.choice([0, 1 << (cw - 1), R.inf_bits(0, w), R.inf_bits(1, w), R.canon_nan(w), 1, (1 << cw) - 2 & ~(1 << (cw - 1)) ^ 0, R.one_bits(w)])
    if k < .25: return random.getrandbits(p - 1) | (random.getrandbits(1) << (cw - 1))
    b = (random.getrandbits(1) << (cw - 1)) | (random.randint(bias - 6, bias + 6) << (p - 1)) | random.getrandbits(p - 1)
    return b
def isnan(b, w): return R.classify(b, w)[0] == 'nan'
def minmax(op, a, b, w, ftz, nan, xs):
    cw = R.CW[w]; SIGN = 1 << (cw - 1)
    if ftz: a, b = R.flush(a, w), R.flush(b, w)
    s = ((a >> (cw - 1)) ^ (b >> (cw - 1))) & 1
    if xs: a, b = a & ~SIGN, b & ~SIGN
    na, nb = isnan(a, w), isnan(b, w)
    if na or nb:
        if nan or (na and nb): return R.canon_nan(w)
        r = b if na else a
    else:
        ka, va, sa = R.classify(a, w); kb, vb, sb = R.classify(b, w)
        x = -va if (sa and va is not None) else (va or 0); y = -vb if (sb and vb is not None) else (vb or 0)
        if ka == 'inf': x = float('inf') if not sa else float('-inf')
        if kb == 'inf': y = float('inf') if not sb else float('-inf')
        if x == y:
            r = (a | b) if op == 'min' else (a & b)
            if x != 0: r = a
        else:
            r = (a if x < y else b) if op == 'min' else (a if x > y else b)
    if xs: r = (r & ~SIGN) | (s << (cw - 1))
    return r
def relu(b, w):
    k, v, s = R.classify(b, w)
    return 0 if (k != 'nan' and s) else b          # negative values and -0.0 -> +0.0

cases = []   # (opcode, kind, width, nin, per-lane function, lanes)
def mk(text, ty, nin, f, packed):
    w = FM[ty.replace('x2', '')]
    rows = []
    for _ in range(N):
        if packed:
            lanes_in = [[rnd(w), rnd(w)] for _ in range(nin)]
            ins = [l[0] | (l[1] << 16) for l in lanes_in]
            out = f(*[l[0] for l in lanes_in]) | (f(*[l[1] for l in lanes_in]) << 16)
        else:
            ins = [rnd(w) for _ in range(nin)]; out = f(*ins)
        rows.append((ins, out))
    cases.append((text, ty, packed, rows))
for ty in ('f16', 'bf16'):
    w = FM[ty]
    for packed in (False, True):
        tt = ty + ('x2' if packed else '')
        for op in ('add', 'sub', 'mul'):
            for mods in ('.rn', '.rn.ftz', '.rn.sat', '.rz'):
                mk(f'{op}{mods}.{tt}', tt, 2, lambda a, b, op=op, mods=mods, w=w: R.ref(op, [a, b], mods.split('.')[1], w, 'ftz' in mods, 'sat' in mods), packed)
        for mods in ('.rn', '.rn.relu', '.rn.sat', '.rn.ftz'):
            mk(f'fma{mods}.{tt}', tt, 3, lambda a, b, c, mods=mods, w=w: (relu(R.ref('fma', [a, b, c], 'rn', w, 'ftz' in mods, False), w) if 'relu' in mods else R.ref('fma', [a, b, c], 'rn', w, 'ftz' in mods, 'sat' in mods)), packed)
        for op in ('min', 'max'):
            for mods in ('', '.NaN', '.xorsign.abs', '.NaN.xorsign.abs', '.ftz'):
                if '.ftz' in mods and ty == 'bf16': continue
                mk(f'{op}{mods}.{tt}', tt, 2, lambda a, b, op=op, mods=mods, w=w: minmax(op, a, b, w, 'ftz' in mods, 'NaN' in mods, 'xorsign' in mods), packed)
        mk(f'neg.{tt}', tt, 1, lambda a, w=w: a ^ (1 << (R.CW[w] - 1)), packed)
        mk(f'abs.{tt}', tt, 1, lambda a, w=w: a & ~(1 << (R.CW[w] - 1)), packed)
cases = cases[PART::PARTS]
print("// GENERATED by scripts/gen_half.py -- half-precision arithmetic (f16, bf16, packed pairs).")
print(".version 8.0\n.target sm_80\n.address_size 64\n")
for k, (text, ty, packed, rows) in enumerate(cases):
    nin = len(rows[0][0]); sz = 4 if packed else 2
    ps = ", ".join(f".param .u64 p{j}" for j in range(nin + 1))
    ld, rg, st = ('b32', '%r', 'b32') if packed else ('b16', '%h', 'b16')
    print(f".visible .entry k{k}({ps})\n{{\n    .reg .b16 %h<10>; .reg .b32 %r<10>; .reg .b64 %rd<6>;\n    mov.u32 %r0, %tid.x; mul.wide.u32 %rd1, %r0, {sz};")
    for j in range(nin):
        print(f"    ld.param.u64 %rd2, [p{j}]; add.s64 %rd2, %rd2, %rd1; ld.global.{ld} {rg}{j+1}, [%rd2];")
    print(f"    {text} {rg}8, {', '.join(f'{rg}{j+1}' for j in range(nin))};")
    print(f"    ld.param.u64 %rd3, [p{nin}]; add.s64 %rd3, %rd3, %rd1; st.global.{st} [%rd3], {rg}8;\n    ret;\n}}\n")
for k, (text, ty, packed, rows) in enumerate(cases):
    nin = len(rows[0][0]); T = 'u32' if packed else 'u16'
    for j in range(nin): print(f".buffer I{k}_{j} .{T} = {{ {', '.join(str(r[0][j]) for r in rows)} }};")
    print(f".buffer O{k} .{T} [{N}];\n.launch k{k} <<< 1, {N} >>> ({', '.join([f'I{k}_{j}' for j in range(nin)] + [f'O{k}'])});")
    print(f".expect O{k} .{T} = {{ {', '.join(str(r[1]) for r in rows)} }};")
