#!/usr/bin/env python3
"""Generate tests/mbar-mc.ptx: mbarrier.expect_tx / complete_tx / arrive{.expect_tx} with .multicast::cluster::32b on a 4-CTA cluster
(every CTA of the mask receives the operation at the same offset).  usage: gen_mbar_mc.py"""
# Each CTA initialises a barrier with 2 expected arrivals.  CTA 0 multicasts, with ctaMask 0b1011 (CTAs 0, 1, 3):
#   expect_tx 64, then complete_tx 64 (net tx 0), then arrive.multicast (count 1) twice -> the barriers of CTAs 0, 1, 3 complete phase 0; CTA 2's does not.
# Every CTA then reports (test_wait.parity of phase 0) whether its barrier completed.
L = """// GENERATED by scripts/gen_mbar_mc.py
.version 8.8
.target sm_100a
.address_size 64

.visible .entry k(.param .u64 po) .reqnctapercluster 4, 1, 1
{
    .reg .b64 %o, %mb, %oo, %t, %st; .reg .b32 %tid, %cta, %bar32, %mask, %one, %w32, %tx; .reg .pred %q, %q0, %w;
    .shared .align 8 .b64 bar;
    ld.param.u64 %o, [po];
    mov.u32 %tid, %tid.x; mov.u32 %cta, %ctaid.x;
    setp.eq.u32 %q, %tid, 0;
    setp.eq.u32 %q0, %cta, 0;
    and.pred %q0, %q0, %q;
    mov.u64 %mb, bar; mov.u32 %bar32, bar;
    mov.u32 %mask, 11; mov.u32 %tx, 64; mov.u32 %one, 1;
    @%q mbarrier.init.shared.b64 [%mb], 2;
    fence.mbarrier_init.release.cluster;
    barrier.cluster.arrive.release.aligned;
    barrier.cluster.wait.acquire.aligned;
    @%q0 mbarrier.expect_tx.relaxed.cluster.shared::cluster.multicast::cluster::32b.b64 [%bar32], %tx, %mask;
    @%q0 mbarrier.arrive.relaxed.cluster.shared::cluster.multicast::cluster::32b.b64 _, [%bar32], %mask;
    @%q0 mbarrier.complete_tx.relaxed.cluster.shared::cluster.multicast::cluster::32b.b64 [%bar32], %tx, %mask;
    @%q0 mbarrier.arrive.expect_tx.relaxed.cluster.shared::cluster.multicast::cluster::32b.b64 _, [%bar32], 0, %mask;
    barrier.cluster.arrive.release.aligned;
    barrier.cluster.wait.acquire.aligned;
    mov.u32 %w32, 0;
    @%q mbarrier.test_wait.parity.shared.b64 %w, [%mb], 0;
    selp.u32 %w32, 1, 0, %w;
    mul.wide.u32 %t, %cta, 4; add.u64 %oo, %o, %t;
    @%q st.global.b32 [%oo], %w32;
    ret;
}
.buffer O .u32 [4];
.launch k <<< 4, 32 >>> (O);
.expect O .u32 = { 1, 1, 0, 1 };
"""
open('tests/mbar-mc.ptx', 'w').write(L)
