#!/usr/bin/env python3
"""Generate tests/tc-*.ptx: tcgen05 alloc / ld / st and tcgen05.mma against a dense model.
Shared-memory tiles reuse the swizzle-atom builder of gen_wgmma.py.  usage: gen_tcgen05.py [SEED]"""
import random, sys, struct
from fractions import Fraction
here = __file__.rsplit('/', 1)[0]
src = open(here + '/gen_wgmma.py').read().split('# name: (N, K')[0]
sys.argv = [sys.argv[0]] + sys.argv[1:2]
exec(compile(src, 'gen_wgmma_prefix', 'exec'))
h = lambda xs: ", ".join(str(x) for x in xs)
HDR = ["// GENERATED by scripts/gen_tcgen05.py", ".version 8.8\n.target sm_100a\n.address_size 64\n"]
def desc100(start, lbo, sbo, z):
    code = {0: 0, 1: 2, 2: 4, 3: 6}[z]
    return ((start >> 4) & 0x3FFF) | (((lbo >> 4) & 0x3FFF) << 16) | (((sbo >> 4) & 0x3FFF) << 32) | (1 << 46) | (code << 61)
CH = 512
def buf(name, ty, vals):
    out = []
    for i in range(0, max(len(vals), 1), CH):
        part = vals[i:i + CH] or [0]
        out.append(f".buffer {name} .{ty} = {{ {h(part)} }};" if i == 0 else f".append {name} .{ty} = {{ {h(part)} }};")
    return "\n".join(out)
def expect(name, ty, vals):
    return "\n".join(f".expect {name} .{ty} @ {i} = {{ {h(vals[i:i + CH])} }};" for i in range(0, len(vals), CH))
vec = lambda p, c: "{" + ", ".join(f"%{p}{i}" for i in range(c)) + "}"

# ---------------------------------------------------------------- alloc / ld / st
STEPS = [("32x32b", 4, ""), ("32x32b", 8, ""), ("16x64b", 4, ""), ("16x128b", 4, ""), ("16x256b", 2, ""), ("16x32bx2", 4, ""), ("32x32b", 4, "pack")]
L = HDR[:]
L.append(""".visible .entry k0(.param .u64 po)
{
    .reg .b32 %r<200>; .reg .b64 %rd<6>; .reg .pred %p, %q; .reg .b32 %t0, %t1, %t2, %t3, %tl, %tw;
    .shared .align 16 .b32 slot[4];
    mov.u32 %tl, %tid.x;
    mov.u64 %rd1, slot;
    setp.lt.u32 %p, %tl, 32;
    setp.eq.u32 %q, %tl, 0;
    @%p tcgen05.alloc.cta_group::1.sync.aligned.shared::cta.b32 [%rd1], 64;
    @%p tcgen05.alloc.cta_group::1.sync.aligned.shared::cta.b32 [%rd1+4], 32;
    @%p tcgen05.alloc.cta_group::1.sync.aligned.shared::cta.b32 [%rd1+8], 32;
    bar.sync 0;
    ld.shared.b32 %t0, [%rd1]; ld.shared.b32 %t1, [%rd1+4]; ld.shared.b32 %t2, [%rd1+8];
    ld.param.u64 %rd2, [po];
    @%q st.global.b32 [%rd2], %t0;
    @%q st.global.b32 [%rd2+4], %t1;
    @%q st.global.b32 [%rd2+8], %t2;
    bar.sync 0;
    @%p tcgen05.dealloc.cta_group::1.sync.aligned.b32 %t1, 32;
    @%p tcgen05.alloc.cta_group::1.sync.aligned.shared::cta.b32 [%rd1+12], 32;
    bar.sync 0;
    ld.shared.b32 %t3, [%rd1+12];
    @%q st.global.b32 [%rd2+12], %t3;
    // ld/st round trips; warp w owns TMEM lanes 32w..32w+31
    shr.u32 %tw, %tl, 5;
    shl.b32 %tw, %tw, 21;                       // lane base << 16 = 32 * warp << 16
    mad.lo.u32 %r199, %tl, 0, 0;
""")
exp = [0, 64, 96, 64]
pos = 16
body = []
for si, (shape, num, mode) in enumerate(STEPS):
    n_ld = num * ({'16x128b': 2, '16x256b': 4}.get(shape, 1))
    vals = [[(t * 1009 + si * 131 + i * 7 + 11) & 0xFFFFFFFF for i in range(n_ld)] for t in range(128)]
    for t in range(128):
        for i in range(n_ld): pass
    taddr = "%tw"
    extra = ", 8" if shape == "16x32bx2" else ""
    stm = f"tcgen05.st.sync.aligned.{shape}.x{num}{'.unpack::16b' if mode == 'pack' else ''}.b32"
    ldm = f"tcgen05.ld.sync.aligned.{shape}.x{num}{'.pack::16b' if mode == 'pack' else ''}.b32"
    nreg = n_ld
    # registers: v values via mad of tid
    body.append(f"    // step {si}: {shape} x{num} {mode}")
    for i in range(nreg):
        body.append(f"    mad.lo.u32 %r{i}, %tl, 1009, {si * 131 + i * 7 + 11};")
    if shape == "16x32bx2": body.append(f"    {stm} [{taddr}], 8, {vec('r', nreg)};")
    else: body.append(f"    {stm} [{taddr}], {vec('r', nreg)};")
    body.append("    tcgen05.wait::st.sync.aligned;\n    bar.sync 0;")
    if shape == "16x32bx2": body.append(f"    {ldm} {vec('r', nreg)[:-1].replace('%r', '%r1')}}}, [{taddr}], 8;".replace("{%r1", "{%r1"))
    else: body.append(f"    {ldm} {vec('r', nreg).replace('%r', '%r1')}, [{taddr}];".replace("%r1", "%r1"))
    exp_vals = vals
    body.append("    tcgen05.wait::ld.sync.aligned;\n    bar.sync 0;")
    body.append(f"    ld.param.u64 %rd2, [po]; mul.wide.u32 %rd3, %tl, {nreg * 4}; add.u64 %rd2, %rd2, %rd3; add.u64 %rd2, %rd2, {pos};")
    for i in range(nreg): body.append(f"    st.global.b32 [%rd2+{i * 4}], %r1{i};")
    # expected: the stored values (identity round trip) -- columns of unused lanes are written twice by t and t+16 only for 16-lane shapes
    pos_here = pos
    exp.append(("rt", pos_here, nreg, vals))
    pos += 128 * nreg * 4
body.append("""    @%p tcgen05.dealloc.cta_group::1.sync.aligned.b32 %t0, 64;
    @%p tcgen05.dealloc.cta_group::1.sync.aligned.b32 %t3, 32;
    @%p tcgen05.dealloc.cta_group::1.sync.aligned.b32 %t2, 32;
    tcgen05.relinquish_alloc_permit.cta_group::1.sync.aligned;
    ret;
}
""")
L.append("\n".join(body))
total = pos
head = exp[:4]
out_words = [0] * (total // 4)
for i, v in enumerate(head): out_words[i] = v
for e in exp[4:]:
    _, p0, nreg, vals = e
    for t in range(128):
        # 16-lane shapes: threads t and t+16 of a warp write distinct cells, so every thread reads back its own value
        for i in range(nreg): out_words[p0 // 4 + t * nreg + i] = vals[t][i]
# the 16x32bx2 / 16xNb thread t reads back what it wrote iff cells are disjoint (they are, see the shapes)
L.append(f".buffer O .u32 [{total // 4}];\n.launch k0 <<< 1, 128 >>> (O);")
L.append(expect('O', 'u32', out_words))
open('tests/tc-0.ptx', 'w').write("\n".join(L) + "\n")
print("tc-0", total // 4, "words")

# ---------------------------------------------------------------- tcgen05.mma
# (N, K, kind, dtype, atype, btype, aform, akm, az, bkm, bz, enable, scale, negA, negB, M, mask, sat)
CFG = [
 (8, 16, 'f16', 'f32', 'f16', 'f16', 'desc', True, 1, True, 1, 1, 0, 0, 0, 128, 0, 0),
 (8, 16, 'f16', 'f32', 'bf16', 'bf16', 'tmem', True, 0, False, 2, 1, 0, 0, 0, 128, 0, 0),
 (8, 16, 'f16', 'f16', 'f16', 'f16', 'desc', True, 0, True, 0, 1, 2, 1, 0, 128, 0, 0),
 (8, 8, 'tf32', 'f32', 'tf32', 'tf32', 'desc', True, 3, True, 3, 0, 0, 0, 1, 64, 0, 0),
 (8, 32, 'i8', 's32', 'u8', 's8', 'desc', True, 1, True, 1, 1, 0, 0, 0, 64, 0, 1),
 (8, 32, 'f8f6f4', 'f32', 'e4m3', 'e5m2', 'desc', True, 1, True, 1, 1, 0, 0, 0, 64, 0, 0),
 (8, 64, 'f8f6f4', 'f32', 'e5m2', 'e4m3', 'desc', True, 2, True, 2, 1, 0, 0, 0, 64, 0, 0),
 (8, 16, 'f16', 'f32', 'f16', 'f16', 'desc', False, 2, False, 3, 1, 0, 0, 0, 64, 0, 0),
 (8, 16, 'f16', 'f32', 'f16', 'f16', 'desc', True, 1, True, 1, 1, 0, 0, 0, 128, (1 << 5) | (1 << 70) | (1 << 127), 0),
]
KIND = {'f16': 'kind::f16', 'tf32': 'kind::tf32', 'i8': 'kind::i8', 'f8f6f4': 'kind::f8f6f4'}
TCODE = {'f16': 0, 'bf16': 1, 'tf32': 2, 'u8': 0, 's8': 1, 'e4m3': 0, 'e5m2': 1}
for kk, (N, K, kind, dt, at, bt, aform, akm, az, bkm, bz, en, sc, na, nb, M, mask, sat) in enumerate(CFG, start=1):
    wa, wb = bw(at), bw(bt)
    small = (dt == 'f16')
    def rnd(ty):
        if small and isflt(ty):
            v = random.choice([-2, -1, -0.5, 0, 0.5, 1, 2, 3]); return struct.unpack('<H', struct.pack('<e', v))[0]
        if isflt(ty): return rand_float_bits(ty)
        return random.getrandbits(bw(ty))
    A = [[rnd(at) for _ in range(K)] for _ in range(M)]
    B = [[rnd(bt) for _ in range(K)] for _ in range(N)]
    Din = {}
    for r in range(M):
        for c in range(N):
            Din[(r, c)] = (struct.unpack('<H', struct.pack('<e', random.choice([-1, 0, 1, 2, 4])))[0] if small else rand_float_bits('f32')) if dt != 's32' else random.choice([0, 1, 100, 0xFFFFFFF0, 0x7FFFFFF0, random.getrandbits(32)])
    neg = lambda ty, bits, s: bits ^ (1 << (bw(ty) - 1)) if (s and isflt(ty)) else bits
    Dout = {}
    for r in range(M):
        for c in range(N):
            if (mask >> r) & 1: Dout[(r, c)] = Din[(r, c)]; continue
            if isflt(at):
                acc = fval(dt, Din[(r, c)]) / (2 ** sc) if en else Fraction(0)
                s = acc + sum(fval(at, neg(at, A[r][k], na)) * fval(bt, neg(bt, B[c][k], nb)) for k in range(K))
                Dout[(r, c)] = to_bits(dt, s)
            else:
                va = (lambda x: sx(x, 8)) if at[0] == 's' else (lambda x: x)
                vb = (lambda x: sx(x, 8)) if bt[0] == 's' else (lambda x: x)
                s = (sx(Din[(r, c)], 32) if en else 0) + sum(va(A[r][k]) * vb(B[c][k]) for k in range(K))
                if sat: s = max(-(1 << 31), min((1 << 31) - 1, s))
                Dout[(r, c)] = s & 0xFFFFFFFF
    img = {}; off = 0; descA = 0
    if aform == 'desc':
        a_img, la, sa_ = build_tile(A, M, K, wa, akm, az, 0)
        img.update(a_img); descA = desc100(0, la, sa_, az)
        off = (max(a_img) + 1 + 1023) // 1024 * 1024
    b_img, lb, sb_ = build_tile(B, N, K, wb, bkm, bz, off)
    img.update(b_img); descB = desc100(off, lb, sb_, bz)
    size = (max(img) + 1 + 2047) // 2048 * 2048
    data = bytes(img.get(i, 0) for i in range(size))
    idesc = (sat << 3) | ({'f16': 0, 'f32': 1, 's32': 2}[dt] << 4) | (TCODE[at] << 7) | (TCODE[bt] << 10) | (na << 13) | (nb << 14) \
          | ((0 if akm else 1) << 15) | ((0 if bkm else 1) << 16) | ((N >> 3) << 17) | ((M >> 4) << 24) | ((1 if (kind == 'f8f6f4' and K == 64) else 0) << 29)
    # A in tensor memory: row r in lane r, K elements packed little endian
    per = 32 // wa
    awords = [[sum(A[r][w * per + j] << (wa * j) for j in range(per)) for w in range(K // per)] for r in range(M)]
    na_cols = K // per
    # registers: thread u owns TMEM lane u (rows 0..127); for M == 64 only lanes 0..63 are used
    nd = N
    L = HDR[:]
    L.append(f""".visible .entry k{kk}(.param .u64 pimg, .param .u64 pd, .param .u64 pa, .param .u64 po)
{{
    .reg .b32 %r<8>, %x<4>, %D<{nd}>, %A<{max(na_cols, 1)}>; .reg .b64 %rd<8>; .reg .b64 %dA, %dB; .reg .b32 %idesc, %tl, %tw, %m0, %m1, %m2, %m3;
    .reg .pred %p, %q;
    .shared .align 1024 .b8 buf[{size}];
    .shared .align 16 .b32 slot[2];
    mov.u32 %tl, %tid.x;
    mov.u64 %rd5, slot;
    setp.lt.u32 %p, %tl, 32;
    setp.eq.u32 %q, %tl, 0;
    @%p tcgen05.alloc.cta_group::1.sync.aligned.shared::cta.b32 [%rd5], 512;
    ld.param.u64 %rd0, [pimg]; mov.u64 %rd2, buf; mul.wide.u32 %rd1, %tl, 16; add.u64 %rd0, %rd0, %rd1; add.u64 %rd2, %rd2, %rd1;""")
    for it in range(size // 2048):
        o = it * 2048
        L.append(f"    ld.global.b32 %x0, [%rd0+{o}]; ld.global.b32 %x1, [%rd0+{o + 4}]; ld.global.b32 %x2, [%rd0+{o + 8}]; ld.global.b32 %x3, [%rd0+{o + 12}];")
        L.append(f"    st.shared.b32 [%rd2+{o}], %x0; st.shared.b32 [%rd2+{o + 4}], %x1; st.shared.b32 [%rd2+{o + 8}], %x2; st.shared.b32 [%rd2+{o + 12}], %x3;")
    L.append("    bar.sync 0;")
    # every thread stores its D row (TMEM lane = thread index) with the warp's lane base; A (tmem form) goes to columns 256..
    L.append(f"    shr.u32 %tw, %tl, 5; shl.b32 %tw, %tw, 21;")
    L.append(f"    ld.param.u64 %rd0, [pd]; mul.wide.u32 %rd1, %tl, {nd * 4}; add.u64 %rd0, %rd0, %rd1;")
    for i in range(nd): L.append(f"    ld.global.b32 %D{i}, [%rd0+{i * 4}];")
    L.append(f"    tcgen05.st.sync.aligned.32x32b.x{nd}.b32 [%tw], {vec('D', nd)};")
    if aform == 'tmem':
        L.append(f"    ld.param.u64 %rd0, [pa]; mul.wide.u32 %rd1, %tl, {na_cols * 4}; add.u64 %rd0, %rd0, %rd1;")
        for i in range(na_cols): L.append(f"    ld.global.b32 %A{i}, [%rd0+{i * 4}];")
        L.append(f"    add.u32 %r1, %tw, 256;\n    tcgen05.st.sync.aligned.32x32b.x{na_cols}.b32 [%r1], {vec('A', na_cols)};")
    L.append("    tcgen05.wait::st.sync.aligned;\n    tcgen05.fence::before_thread_sync;\n    bar.sync 0;")
    L.append(f"    mov.b64 %dB, {descB};\n    mov.b32 %idesc, {idesc};")
    for i in range(4): L.append(f"    mov.b32 %m{i}, {(mask >> (32 * i)) & 0xFFFFFFFF};")
    a_op = "%dA" if aform == 'desc' else "[%r2]"
    if aform == 'desc': L.append(f"    mov.b64 %dA, {descA};")
    else: L.append("    mov.u32 %r2, 256;")
    scale_arg = f", {sc}" if kind in ('f16', 'tf32') else ""
    L.append(f"    @%q tcgen05.mma.cta_group::1.{KIND[kind]} [%r3], {a_op}, %dB, %idesc, {{%m0, %m1, %m2, %m3}}, {en}{scale_arg};".replace("[%r3]", "[%r3]"))
    L.append("    tcgen05.fence::after_thread_sync;\n    bar.sync 0;")
    L.append(f"    tcgen05.ld.sync.aligned.32x32b.x{nd}.b32 {vec('D', nd)}, [%tw];\n    tcgen05.wait::ld.sync.aligned;")
    L.append(f"    ld.param.u64 %rd0, [po]; mul.wide.u32 %rd1, %tl, {nd * 4}; add.u64 %rd0, %rd0, %rd1;")
    for i in range(nd): L.append(f"    st.global.b32 [%rd0+{i * 4}], %D{i};")
    L.append("    bar.sync 0;\n    @%p tcgen05.dealloc.cta_group::1.sync.aligned.b32 %r4, 512;\n    ret;\n}\n")
    # r3 = D taddr 0 (lane 0, col 0) set at start
    L[-1] = L[-1].replace("    ret;", "    ret;")
    code = "\n".join(L)
    code = code.replace("    mov.u32 %tl, %tid.x;", "    mov.u32 %tl, %tid.x;\n    mov.u32 %r3, 0; mov.u32 %r4, 0;", 1)
    flat = lambda rows: [x for r in rows for x in r]
    din = [[Din[(u, c)] if u < M else 0 for c in range(N)] for u in range(128)]
    dout = [[Dout[(u, c)] if u < M else 0 for c in range(N)] for u in range(128)]
    # lanes >= M are never written by the mma: they read back what was stored (0)
    code += "\n" + buf('IMG', 'u8', [])[:0]
    code += f".buffer IMG .u8 [{len(data)}];\n"
    i = 0
    while i < len(data):
        if data[i] == 0: i += 1; continue
        j = i
        while j < len(data) and (j - i < 400) and not (data[j] == 0 and all(x == 0 for x in data[j:j + 16])): j += 1
        code += f".patch IMG .u8 @ {i} = {{ {h(data[i:j])} }};\n"
        i = j
    code += buf('DIN', 'u32', flat(din)) + "\n"
    code += buf('AIN', 'u32', flat(awords + [[0] * na_cols for _ in range(128 - M)]) if aform == 'tmem' else [0]) + "\n"
    code += f".buffer O .u32 [{128 * nd}];\n.launch k{kk} <<< 1, 128 >>> (IMG, DIN, AIN, O);\n" + expect('O', 'u32', flat(dout)) + "\n"
    open(f'tests/tc-{kk}.ptx', 'w').write(code)
print(len(CFG) + 1, "tests")
