#!/usr/bin/env python3
"""Generate tests/pred.ptx: set, slct, testp vs Python models.
usage: gen_pred.py [N] [SEED] [PART] [PARTS]   (parts keep each K program small)"""
import math, random, struct, sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 24
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 6)
M32 = (1 << 32) - 1
def f32(b): return struct.unpack('<f', struct.pack('<I', b))[0]
def b32(x): return struct.unpack('<I', struct.pack('<f', x))[0]
def s32(x): return x - (1 << 32) if x >> 31 else x
def rf():
    return random.choice([0, 0x80000000, 0x7F800000, 0xFF800000, 0x7FC00000, 0x00000001, 0x80000001, 0x00800000,
                          0x3F800000, 0xBF800000, 0x007FFFFF]) if random.random() < .5 else random.getrandbits(32)
def ri(): return random.choice([0, M32, 0x80000000, 0x7FFFFFFF, 1]) if random.random() < .4 else random.getrandbits(32)
def subn(b): return (b >> 23) & 0xFF == 0 and b & 0x7FFFFF != 0
def ftz(b): return b & 0x80000000 if subn(b) else b
def cmpf(op, x, y):
    nan = math.isnan(x) or math.isnan(y)
    if op == 'num': return not nan
    if op == 'nan': return nan
    if op.endswith('u') and op not in ('lo',): return True if nan else cmpf(op[:-1], x, y)
    if nan: return False
    return {'eq': x == y, 'ne': x != y, 'lt': x < y, 'le': x <= y, 'gt': x > y, 'ge': x >= y}[op]
def cmpi(op, a, b, signed):
    x, y = (s32(a), s32(b)) if signed and op in ('eq', 'ne', 'lt', 'le', 'gt', 'ge') else (a, b)
    return {'eq': x == y, 'ne': x != y, 'lt': x < y, 'le': x <= y, 'gt': x > y, 'ge': x >= y,
            'lo': a < b, 'ls': a <= b, 'hi': a > b, 'hs': a >= b}[op]
ONE = b32(1.0)
cases = []  # (opcode text, nops, inputs per op (list of lists), expected)
def mk(op, ins, f, rw=32):
    cases.append((op, ins, [f(*[col[i] for col in ins]) & M32 for i in range(N)]))
FL = ['eq', 'ne', 'lt', 'le', 'gt', 'ge', 'equ', 'neu', 'ltu', 'leu', 'gtu', 'geu', 'num', 'nan']
for op in FL:
    A = [rf() for _ in range(N)]; B = [rf() for _ in range(N)]
    for dt in ('u32', 's32', 'f32'):
        mk(f'set.{op}.{dt}.f32', [A, B], lambda a, b, op=op, dt=dt: (ONE if dt == 'f32' else M32) if cmpf(op, f32(a), f32(b)) else 0)
    mk(f'set.{op}.ftz.u32.f32', [A, B], lambda a, b, op=op: M32 if cmpf(op, f32(ftz(a)), f32(ftz(b))) else 0)
    C = [random.getrandbits(1) for _ in range(N)]
    mk(f'set.{op}.and.u32.f32', [A, B, C], lambda a, b, c, op=op: M32 if (cmpf(op, f32(a), f32(b)) and c) else 0)
    mk(f'set.{op}.xor.u32.f32', [A, B, C], lambda a, b, c, op=op: M32 if (cmpf(op, f32(a), f32(b)) != bool(c)) else 0)
for op in ['eq', 'ne', 'lt', 'le', 'gt', 'ge', 'lo', 'ls', 'hi', 'hs']:
    A = [ri() for _ in range(N)]; B = [ri() for _ in range(N)]
    for st in ('u32', 's32'):
        if op in ('lo', 'ls', 'hi', 'hs') and st == 's32': continue
        mk(f'set.{op}.u32.{st}', [A, B], lambda a, b, op=op, st=st: M32 if cmpi(op, a, b, st == 's32') else 0)
        mk(f'set.{op}.f32.{st}', [A, B], lambda a, b, op=op, st=st: ONE if cmpi(op, a, b, st == 's32') else 0)
# slct
A = [ri() for _ in range(N)]; B = [ri() for _ in range(N)]; CI = [ri() for _ in range(N)]; CF = [rf() for _ in range(N)]
mk('slct.u32.s32', [A, B, CI], lambda a, b, c: a if s32(c) >= 0 else b)
mk('slct.s32.s32', [A, B, CI], lambda a, b, c: a if s32(c) >= 0 else b)
mk('slct.b32.f32', [A, B, CF], lambda a, b, c: a if (not math.isnan(f32(c)) and f32(c) >= 0) else b)
mk('slct.ftz.b32.f32', [A, B, CF], lambda a, b, c: a if (not math.isnan(f32(ftz(c))) and f32(ftz(c)) >= 0) else b)
# testp
X = [rf() for _ in range(N)]
def cls(b):
    e = (b >> 23) & 0xFF; m = b & 0x7FFFFF
    return {'finite': e != 255, 'infinite': e == 255 and m == 0, 'number': not (e == 255 and m != 0),
            'notanumber': e == 255 and m != 0, 'normal': 0 < e < 255, 'subnormal': e == 0 and m != 0}
for op in ('finite', 'infinite', 'number', 'notanumber', 'normal', 'subnormal'):
    mk(f'testp.{op}.f32', [X], lambda a, op=op: 1 if cls(a)[op] else 0)

PART = int(sys.argv[3]) if len(sys.argv) > 3 else 0
PARTS = int(sys.argv[4]) if len(sys.argv) > 4 else 1
cases = cases[PART::PARTS]
print("// GENERATED by scripts/gen_pred.py -- set, slct, testp against Python models.")
print(".version 8.0\n.target sm_80\n.address_size 64\n")
# group kernels so each has a modest size: one kernel per opcode
for k, (op, ins, exp) in enumerate(cases):
    n = len(ins)
    ps = ", ".join(f".param .u64 p{j}" for j in range(n + 1))
    print(f".visible .entry k{k}({ps})\n{{\n    .reg .b32 %r<10>; .reg .b64 %rd<6>; .reg .pred %p<4>;\n    mov.u32 %r0, %tid.x; mul.wide.u32 %rd1, %r0, 4;")
    for j in range(n):
        print(f"    ld.param.u64 %rd2, [p{j}]; add.s64 %rd2, %rd2, %rd1; ld.global.b32 %r{4+j}, [%rd2];")
    base = op.split('.')[0]
    if base == 'testp':
        print(f"    {op} %p1, %r4;\n    selp.u32 %r1, 1, 0, %p1;")
    elif base == 'set' and n == 3:
        print(f"    setp.ne.u32 %p2, %r6, 0;\n    {op} %r1, %r4, %r5, %p2;")
    else:
        print(f"    {op} %r1, {', '.join('%r' + str(4 + j) for j in range(n))};")
    print(f"    ld.param.u64 %rd3, [p{n}]; add.s64 %rd3, %rd3, %rd1; st.global.b32 [%rd3], %r1;\n    ret;\n}}\n")
for k, (op, ins, exp) in enumerate(cases):
    for j, col in enumerate(ins):
        print(f".buffer I{k}_{j} .u32 = {{ {', '.join(map(str, col))} }};")
    print(f".buffer O{k} .u32 [{N}];\n.launch k{k} <<< 1, {N} >>> ({', '.join([f'I{k}_{j}' for j in range(len(ins))] + [f'O{k}'])});")
    print(f".expect O{k} .u32 = {{ {', '.join(map(str, exp))} }};")
