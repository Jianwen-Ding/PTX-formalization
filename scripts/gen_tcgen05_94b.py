def pack_sub(X, nb, padded):
    """K-major rows of 6- / 4-bit codes -> rows of bytes: padding after every 16 elements (16 bytes per 16 elements) or
    contiguous (9.7.18.10.4.4, Figures 207-209)"""
    K = len(X[0])
    nbytes = K if padded else K * nb // 8
    out = []
    for row in X:
        bits = 0
        for k, v in enumerate(row):
            bits |= v << (128 * (k // 16) + (k % 16) * nb if padded else k * nb)
        out.append([(bits >> (8 * i)) & 255 for i in range(nbytes)])
    return out

def sfw128(S, n, nb, sid, l, col):
    """128-lane scale_A layout: row l in lane l, byte sid + j in column (sid + j) / 4"""
    return sum(S[l][j] << (8 * ((sid + j) % 4)) for j in range(nb) if l < n and (sid + j) // 4 == col)

def sparse_rows(M, K, at, cw, ver):
    """a 2:4 (cw 4) or pair-wise 4:8 (cw 8) sparse A: (dense rows, packed rows, nibbles[r][c])"""
    A = [[0] * K for _ in range(M)]
    packed = [[] for _ in range(M)]
    nibs = [[] for _ in range(M)]
    for r in range(M):
        for c in range(K // cw):
            v = random.choice(NIBS); nibs[r].append(v)
            if cw == 4:
                vals = [rand_float_bits(at) for _ in range(2)]
                for j in range(2): A[r][4 * c + ((v >> (2 * j)) & 3)] = vals[j]
            else:                                   # pair-wise: element j in sub-chunk index (v >> 2 (j / 2)) & 3
                vals = [rand_float_bits(at) for _ in range(4)]
                for j in range(4): A[r][8 * c + 2 * ((v >> (2 * (j // 2))) & 3) + j % 2] = vals[j]
            packed[r] += vals
    return A, packed, nibs

def case(kk, kind, vq, at, bt, N, K, blk, sfa, sfb, en, sparse=None, l128=False, a_tmem=False, target='sm_107f',
         path=None, first='', directives=''):
    """block-scaled (UE8M0) M = 128 mma; sparse: 'v0' / 'v1' (.kind::mxf4*) or '24' (.kind::mxf8f6f4); K is the full K"""
    M = 128
    mx4 = kind != 'kind::mxf8f6f4'
    nb = K // blk
    dk = K // 2 if sparse else K                    # the Dense-K dimension (the idesc K field)
    cw = 8 if sparse == 'v0' else 4
    if sparse:
        A, packed, nibs = sparse_rows(M, K, at, cw, sparse)
    else:
        A = [[rand_float_bits(at) for _ in range(K)] for _ in range(M)]; packed = A
    B = [[rand_float_bits(bt) for _ in range(K)] for _ in range(N)]
    SA = [[random.randint(122, 131) for _ in range(nb)] for _ in range(M)]
    SB = [[random.randint(122, 131) for _ in range(nb)] for _ in range(N)]
    Din = [[rand_float_bits('f32') for _ in range(N)] for _ in range(M)]
    kp = len(packed[0])
    img = {}; descA = 0; off = 0; extra = []
    sub = lambda t: t in ('e2m3', 'e3m2', 'e2m1')
    nbits = lambda t: 4 if t == 'e2m1' else 6
    if not a_tmem:
        if mx4: a_img, la, sa_ = build_tile(packed, M, kp, 4, True, 1, 0)
        elif sub(at):
            ab = pack_sub(packed, nbits(at), dk == 32)
            a_img, la, sa_ = build_tile(ab, M, len(ab[0]), 8, True, 1, 0)
        else: a_img, la, sa_ = build_tile(packed, M, kp, 8, True, 1, 0)
        img.update(a_img); descA = desc100(0, la, sa_, 1); off = (max(a_img) + 1 + 1023) // 1024 * 1024
    else:
        AC = 200
        assert at in ('e2m3', 'e3m2') and dk == 64 and not sparse
        words = []
        for r in range(128):
            bits = sum(A[r][k] << (6 * k) for k in range(K)) if r < M else random.getrandbits(384)
            words.append([(bits >> (32 * i)) & 0xFFFFFFFF for i in range(12)])
        extra += [(AC, 6, [w[:6] for w in words]), (AC + 6, 6, [w[6:] for w in words])]
    if mx4: b_img, lb, sb_ = build_tile(B, N, K, 4, True, 1, off)
    elif sub(bt):
        bb = pack_sub(B, nbits(bt), dk == 32)
        b_img, lb, sb_ = build_tile(bb, N, len(bb[0]), 8, True, 1, off)
    else: b_img, lb, sb_ = build_tile(B, N, K, 8, True, 1, off)
    img.update(b_img); descB = desc100(off, lb, sb_, 1)
    size, data = image(img)
    Dout = [[to_bits('f32', (fval('f32', Din[r][c]) if en else 0)
                     + sum(fval(at, A[r][k]) * fval(bt, B[c][k]) * ue8m0(SA[r][k // blk]) * ue8m0(SB[c][k // blk]) for k in range(K)))
             for c in range(N)] for r in range(M)]
    TC = {'e4m3': 0, 'e5m2': 1, 'e2m3': 3, 'e3m2': 4, 'e2m1': 1 if mx4 else 5}
    idesc = ((1 if sparse else 0) << 2) | (sfb << 4) | (TC[at] << 7) | (TC[bt] << 10) | ((N >> 3) << 17) | (1 << 23) \
          | ((1 if l128 else 0) << 26) | ((M >> 7) << 27) | (sfa << 29)
    if mx4:
        kf = {64: 0, 96: 1, 128: 2}[dk]
        idesc |= ((kf >> 1) << 3) | ((kf & 1) << 31) | ((1 if sparse == 'v1' else 0) << 12)
    else:
        idesc |= (1 if dk == 64 else 0) << 31
    SAC, SBC, MC = 300, 310, 320
    extra += [(SAC, 8, [[(sfw128 if l128 else sfw)(SA, M, nb, sfa, l, col) for col in range(8)] for l in range(128)]),
              (SBC, 8, [[sfw(SB, N, nb, sfb, l, col) for col in range(8)] for l in range(128)])]
    if sparse:
        nc = len(nibs[0])                           # 16 or 32 nibbles: 2 or 4 columns
        mw = [[sum(nibs[l][8 * col + i] << (4 * i) for i in range(8)) if l < M else random.getrandbits(32) for col in range(nc // 8)]
              for l in range(128)]
        extra.append((MC, nc // 8, mw))
    setup = [f"mov.b64 %dB, {descB};", f"mov.b64 %dA, {descA};", f"mov.b32 %idesc, {idesc};", f"mov.u32 %r8, {SAC};",
             f"mov.u32 %r9, {SBC};", f"mov.u32 %r7, {MC};", f"mov.u32 %r2, {200};"]
    a_op = '[%r2]' if a_tmem else '%dA'
    if sparse:
        mma = f"tcgen05.mma.sp.cta_group::1.{kind}.block_scale{vq} [%r3], {a_op}, %dB, [%r7], %idesc, [%r8], [%r9], {en};"
    else:
        mma = f"tcgen05.mma.cta_group::1.{kind}.block_scale{vq} [%r3], {a_op}, %dB, %idesc, [%r8], [%r9], {en};"
    din = flat([[Din[u][c] for c in range(N)] for u in range(128)])
    dout = flat([[Dout[u][c] for c in range(N)] for u in range(128)])
    code = program(kk, data, N, din, None if path else dout, 'u32', extra, setup, [mma], directives, target=target, first=first)
    open(path or f'tests/tc-94b-{kk}.ptx', 'w').write(code)

