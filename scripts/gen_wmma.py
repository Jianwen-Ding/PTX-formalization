#!/usr/bin/env python3
"""Generate tests/wmma.ptx: wmma.load -> wmma.mma -> wmma.store round trips against an
exact integer/rational matmul.  Fragment layouts of wmma are unspecified in PTX, so
only the memory-to-memory behaviour is checked (A row-major, B column-major)."""
import random, struct
random.seed(5)
def enc(ty, v):
    if ty == 'f16': return struct.pack('<e', v)
    if ty == 'bf16': return struct.pack('<f', v)[2:]
    if ty in ('f32', 'tf32'): return struct.pack('<f', v)
    if ty == 'f64': return struct.pack('<d', v)
    if ty == 's32': return struct.pack('<i', v)
    if ty == 's8': return struct.pack('<b', v)
def pack_bits(vals, w):
    n = 8 // w; out = []
    for i in range(0, len(vals), n):
        b = 0
        for j, v in enumerate(vals[i:i + n]): b |= (v & ((1 << w) - 1)) << (j * w)
        out.append(b)
    return bytes(out)
def bufbytes(vals, ty):
    if ty == 's4': return pack_bits(vals, 4)
    if ty == 'b1': return pack_bits(vals, 1)
    return b''.join(enc(ty, v) for v in vals)
# name, shape, abty, cty, regs a/b/c, extra mma modifier
CFG = [('f16', 'm16n16k16', 'f16', 'f32', 8, 8, 8, ''),
       ('bf16', 'm16n16k16', 'bf16', 'f32', 4, 4, 8, ''),
       ('s8', 'm16n16k16', 's8', 's32', 2, 2, 8, ''),
       ('tf32', 'm16n16k8', 'tf32', 'f32', 4, 4, 8, ''),
       ('f64', 'm8n8k4', 'f64', 'f64', 1, 1, 2, ''),
       ('s4', 'm8n8k32', 's4', 's32', 1, 1, 2, ''),
       ('b1', 'm8n8k128', 'b1', 's32', 1, 1, 2, '.xor.popc')]
HDR = ["// GENERATED by scripts/gen_wmma.py -- wmma.load/mma/store round trips vs. an exact matmul",
       ".version 8.0\n.target sm_90\n.address_size 64\n"]
for k, (nm, sh, ab, cty, na, nb, nc, xm) in enumerate(CFG):
    m, n, kk = [int(x) for x in sh[1:].replace('n', ' ').replace('k', ' ').split()]
    if ab in ('f16', 'bf16', 'tf32', 'f64'): rv = lambda: random.randint(-8, 8)
    elif ab == 's8': rv = lambda: random.randint(-128, 127)
    elif ab == 's4': rv = lambda: random.randint(-8, 7)
    else: rv = lambda: random.randint(0, 1)
    A = [[rv() for _ in range(kk)] for _ in range(m)]
    B = [[rv() for _ in range(n)] for _ in range(kk)]
    C = [[random.randint(-50, 50) for _ in range(n)] for _ in range(m)]
    if cty == 'f64': C = [[float(x) for x in r] for r in C]
    D = []
    for i in range(m):
        row = []
        for j in range(n):
            if ab == 'b1': s = sum(A[i][t] ^ B[t][j] for t in range(kk))
            else: s = sum(A[i][t] * B[t][j] for t in range(kk))
            row.append(C[i][j] + s)
        D.append(row)
    flat = lambda M: [x for r in M for x in r]
    Ab = bufbytes(flat(A), ab)
    Bb = bufbytes([B[r][c] for c in range(n) for r in range(kk)], ab)      # column-major
    Cb = bufbytes(flat(C), cty); Db = bufbytes(flat(D), cty)
    wide = 'b64' if ab == 'f64' else 'b32'
    ctyr = 'b64' if cty == 'f64' else 'b32'
    def regs(p, c, t): return "{" + ", ".join(f"%{p}{i}" for i in range(c)) + "}"
    ldty = lambda t: t
    ctr = cty
    body = f""".visible .entry k{k}(.param .u64 pa, .param .u64 pb, .param .u64 pc, .param .u64 po)
{{
    .reg .b64 %pa, %pb, %pc, %po;
    .reg .{wide} %A<{na}>; .reg .{wide} %B<{nb}>; .reg .{ctyr} %C<{nc}>; .reg .{ctyr} %D<{nc}>;
    ld.param.u64 %pa, [pa]; ld.param.u64 %pb, [pb]; ld.param.u64 %pc, [pc]; ld.param.u64 %po, [po];
    wmma.load.a.sync.aligned.row.{sh}.global.{ab} {regs('A', na, ab)}, [%pa], {kk};
    wmma.load.b.sync.aligned.col.{sh}.global.{ab} {regs('B', nb, ab)}, [%pb], {kk};
    wmma.load.c.sync.aligned.row.{sh}.global.{cty} {regs('C', nc, cty)}, [%pc], {n};
    wmma.mma{xm}.sync.aligned.row.col.{sh}.{cty}.{ab}.{ab}.{cty} {regs('D', nc, cty)}, {regs('A', na, ab)}, {regs('B', nb, ab)}, {regs('C', nc, cty)};
    wmma.store.d.sync.aligned.row.{sh}.global.{cty} [%po], {regs('D', nc, cty)}, {n};
    ret;
}}
"""
    out = HDR + [body]
    tail = []
    h = lambda b: ", ".join(str(x) for x in b)
    tail.append(f".buffer A{k} .u8 = {{ {h(Ab)} }};\n.buffer B{k} .u8 = {{ {h(Bb)} }};\n.buffer C{k} .u8 = {{ {h(Cb)} }};\n.buffer O{k} .u8 [{len(Db)}];\n"
                f".launch k{k} <<< 1, 32 >>> (A{k}, B{k}, C{k}, O{k});\n.expect O{k} .u8 = {{ {h(Db)} }};")
    open(f'tests/wmma-{k}.ptx', 'w').write("\n".join(out) + "\n" + "\n".join(tail) + "\n")
