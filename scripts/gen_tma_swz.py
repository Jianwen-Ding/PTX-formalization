#!/usr/bin/env python3
"""Generate tests/tma-swz-*.ptx: 2D tile loads with every swizzle mode of the tensor map (32B, 64B, 128B, 128B with 32B / 32B+8B-flip / 64B atomicity),
and an out-of-bounds NaN fill for f16 / bf16 / f32, against the destination-layout tables of the PTX ISA (section 5.5.7, "Swizzling Modes").
usage: gen_tma_swz.py"""
import random, struct
random.seed(5)
h = lambda xs: ", ".join(str(x) for x in xs)
def perm_chunk(mode, c, line):
    """16-byte chunk c (0..7) of 128-byte line `line` -> destination chunk (ISA tables)"""
    if mode == 'none': return c
    if mode == '32': return c ^ (line % 2)
    if mode == '64': return (c & 4) | ((c & 3) ^ (line % 4))
    if mode == '128': return c ^ (line % 8)
    if mode == '128a32': return 2 * ((c >> 1) ^ (line % 4)) + (c & 1)
    if mode == '128a32f': return 2 * ((c >> 1) ^ (line % 4)) + (c & 1)
    if mode == '128a64': return c ^ (4 * (line % 2))
CODES = {'none': 0, '32': 1, '64': 2, '128': 3, '128a32': 4, '128a32f': 5, '128a64': 6}
def swz_image(mode, img):                     # img: list of bytes of the dense box image
    out = [0] * len(img)
    for b in range(len(img)):
        line, c, off = b // 128, (b // 16) % 8, b % 16
        d = line * 128 + perm_chunk(mode, c, line) * 16 + off
        if mode == '128a32f' and line % 2 == 1: d ^= 8      # flip adjacent 8-byte halves of the 16-byte chunk on odd lines
        out[d] = img[b]
    return out
def test(name, mode, dtype, fill, dims, box, coords, elem_bytes, nan_bits=None):
    code = CODES[mode]
    N = dims[0] * dims[1]
    vals = [random.randint(1, 60000) if elem_bytes == 2 else random.getrandbits(32) for _ in range(N)]
    img = []
    for r in range(box[1]):
        for c in range(box[0]):
            x, y = coords[0] + c, coords[1] + r
            if 0 <= x < dims[0] and 0 <= y < dims[1]: v = vals[y * dims[0] + x]
            else: v = nan_bits if fill else 0
            img += [(v >> (8 * i)) & 255 for i in range(elem_bytes)]
    sw = swz_image(mode, img)
    nb = len(img)
    words = [sum(sw[4 * i + j] << (8 * j) for j in range(4)) for i in range(nb // 4)]
    # the fill mode rides in bits 8.. of the swizzle value
    tm = f".tensormap TM {dtype} G .dims {{ {h(dims)} }} .strides {{ {dims[0] * elem_bytes} }} .box {{ {h(box)} }} .swizzle {code + (256 if fill else 0)} ;"
    L = [f"// GENERATED by scripts/gen_tma_swz.py -- {name}", ".version 8.6\n.target sm_100a\n.address_size 64\n",
         f""".visible .entry k(.param .u64 ptm, .param .u64 po)
{{
    .reg .b64 %tm, %o, %mb, %st, %t, %sa, %oo; .reg .b32 %tid, %buf32, %bar32, %x; .reg .pred %q, %w;
    .shared .align 1024 .b8 buf[{(nb + 1023) // 1024 * 1024}];
    .shared .align 8 .b64 bar;
    ld.param.u64 %tm, [ptm]; ld.param.u64 %o, [po];
    mov.u32 %tid, %tid.x;
    setp.eq.u32 %q, %tid, 0;
    mov.u64 %mb, bar; mov.u32 %bar32, bar; mov.u32 %buf32, buf;
    @%q mbarrier.init.shared.b64 [%mb], 1;
    bar.sync 0;
    @%q mbarrier.arrive.expect_tx.shared.b64 %st, [%mb], {nb};
    @%q cp.async.bulk.tensor.2d.shared::cluster.global.tile.mbarrier::complete_tx::bytes [%buf32], [%tm, {{{h(coords)}}}], [%bar32];
    @%q mbarrier.try_wait.parity.shared.b64 %w, [%mb], 0;
    bar.sync 0;
    mul.wide.u32 %t, %tid, 4;
    mov.u64 %sa, buf; add.u64 %sa, %sa, %t; add.u64 %oo, %o, %t;"""]
    for i in range(0, nb // 4, 32): L.append(f"    ld.shared.b32 %x, [%sa+{4 * i}]; st.global.b32 [%oo+{4 * i}], %x;")
    L.append("    ret;\n}\n")
    gty = 'u16' if elem_bytes == 2 else 'u32'
    L.append(f".buffer G .{gty} = {{ {h(vals)} }};\n{tm}\n.buffer O .u32 [{len(words)}];\n.launch k <<< 1, 32 >>> (TM, O);\n.expect O .u32 = {{ {h(words)} }};")
    open(f'tests/tma-swz-{name}.ptx', 'w').write("\n".join(L) + "\n")
for m in CODES:
    test(m, m, '.f16', False, [64, 32], [64, 16], [0, 4], 2)
# out-of-bounds NaN fill
test('nan16', 'none', '.f16', True, [10, 6], [16, 8], [4, 2], 2, 0x7e00)
test('nanbf', 'none', '.bf16', True, [10, 6], [16, 8], [4, 2], 2, 0x7fc0)
test('nan32', 'none', '.f32', True, [10, 6], [8, 8], [4, 2], 4, 0x7fc00000)
print("ok")
