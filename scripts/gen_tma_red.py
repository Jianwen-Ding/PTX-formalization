#!/usr/bin/env python3
"""Generate tests/tma-red.ptx (cp.reduce.async.bulk.tensor for every .redOp / element-type pair of the ISA table) and tests/tma-mc*.ptx
(multicast::cluster with 16-bit / 32-bit masks and cta_group::2 mbarrier signalling) against direct models.  usage: gen_tma_red.py"""
import random, struct
random.seed(23)
h = lambda xs: ", ".join(str(x) for x in xs)
M32 = (1 << 32) - 1; M64 = (1 << 64) - 1
def sg(x, w): return x - (1 << w) if x >> (w - 1) else x
def f32(x): return struct.unpack('<f', struct.pack('<f', x))[0]
def f32b(x): return struct.unpack('<I', struct.pack('<f', x))[0]
def b2f32(b): return struct.unpack('<f', struct.pack('<I', b))[0]
def f16b(x): return struct.unpack('<H', struct.pack('<e', x))[0]
def b2f16(b): return struct.unpack('<e', struct.pack('<H', b))[0]
def bf16b(x): b = f32b(x); b += 0x7fff + ((b >> 16) & 1); return (b >> 16) & 0xffff      # round to nearest even
def b2bf(b): return b2f32(b << 16)
TYPES = {'u32': (32, 'u32'), 's32': (32, 's32'), 'u64': (64, 'u64'), 's64': (64, 's64'), 'f32': (32, 'f32'), 'f16': (16, 'f16'), 'bf16': (16, 'bf16')}
def rnd(ty):
    w = TYPES[ty][0]
    if ty == 'f32': return f32b(random.choice([-1, 1]) * random.choice([0.5, 1.25, 3.0, 7.5, 100.0]))
    if ty == 'f16': return f16b(random.choice([-1, 1]) * random.choice([0.5, 1.25, 3.0, 7.5, 100.0]))
    if ty == 'bf16': return bf16b(random.choice([-1, 1]) * random.choice([0.5, 1.25, 3.0, 7.5, 100.0]))
    return random.getrandbits(w)
def combine(op, ty, old, v):
    w = TYPES[ty][0]
    if ty in ('f32', 'f16', 'bf16'):
        a, b = {'f32': b2f32, 'f16': b2f16, 'bf16': b2bf}[ty](old), {'f32': b2f32, 'f16': b2f16, 'bf16': b2bf}[ty](v)
        if op == 'add': r = a + b
        elif op == 'min': r = min(a, b)
        else: r = max(a, b)
        return {'f32': f32b, 'f16': f16b, 'bf16': bf16b}[ty](r)
    s = (lambda x: sg(x, w)) if ty[0] == 's' else (lambda x: x)
    if op == 'add': return (old + v) & ((1 << w) - 1)
    if op == 'min': return old if s(old) <= s(v) else v
    if op == 'max': return old if s(old) >= s(v) else v
    if op == 'inc': return 0 if old >= v else old + 1
    if op == 'dec': return v if (old == 0 or old > v) else old - 1
    if op == 'and': return old & v
    if op == 'or': return old | v
    if op == 'xor': return old ^ v
COMBOS = ([('add', t) for t in ('u32', 's32', 'u64', 'f32', 'f16', 'bf16')] + [(o, t) for o in ('min', 'max') for t in ('u32', 's32', 'u64', 's64', 'f16', 'bf16')]
          + [('inc', 'u32'), ('dec', 'u32')] + [(o, t) for o in ('and', 'or', 'xor') for t in ('u32', 'u64')])
N = 16
L = ["// GENERATED by scripts/gen_tma_red.py -- cp.reduce.async.bulk.tensor for every redOp / element-type combination", ".version 8.6\n.target sm_100a\n.address_size 64\n"]
tail = []
for kk, (op, ty) in enumerate(COMBOS):
    w = TYPES[ty][0]; eb = w // 8
    dst = [rnd(ty) for _ in range(N)]
    src = [rnd(ty) for _ in range(N)]
    if op in ('inc', 'dec'):
        dst = [random.randint(0, 9) for _ in range(N)]; src = [random.randint(1, 9) for _ in range(N)]
    out = [combine(op, ty, d, s) for d, s in zip(dst, src)]
    nbytes = N * eb
    # shared image: the source elements
    wordsv = []
    raw = b"".join(s.to_bytes(eb, 'little') for s in src)
    words = [int.from_bytes(raw[4 * i:4 * i + 4], 'little') for i in range(nbytes // 4)]
    gty = {'u32': 'u32', 's32': 's32', 'u64': 'u64', 's64': 's64', 'f32': 'f32', 'f16': 'f16', 'bf16': 'bf16'}[ty]
    # harness element types for the buffers: use integer views
    bty = {1: 'u8', 2: 'u16', 4: 'u32', 8: 'u64'}[eb]
    L.append(f""".visible .entry k{kk}(.param .u64 ptm, .param .u64 pin)
{{
    .reg .b64 %tm, %in, %t, %sa, %ia; .reg .b32 %tid, %buf32, %x; .reg .pred %q;
    .shared .align 1024 .b8 buf[1024];
    ld.param.u64 %tm, [ptm]; ld.param.u64 %in, [pin];
    mov.u32 %tid, %tid.x;
    setp.eq.u32 %q, %tid, 0;
    mov.u32 %buf32, buf;
    mul.wide.u32 %t, %tid, 4;
    mov.u64 %sa, buf; add.u64 %sa, %sa, %t; add.u64 %ia, %in, %t;""")
    for i in range(0, nbytes // 4, 32):
        L.append(f"    @%q2 ld.global.b32 %x, [%ia+{4 * i}]; st.shared.b32 [%sa+{4 * i}], %x;".replace("@%q2 ", "") if False else f"    ld.global.b32 %x, [%ia+{4 * i}]; st.shared.b32 [%sa+{4 * i}], %x;")
    L.append(f"""    fence.proxy.async.shared::cta;
    bar.sync 0;
    @%q cp.reduce.async.bulk.tensor.1d.global.shared::cta.{op}.tile.bulk_group [%tm, {{0}}], [%buf32];
    @%q cp.async.bulk.commit_group;
    @%q cp.async.bulk.wait_group 0;
    ret;
}}
""")
    dstraw = b"".join(d.to_bytes(eb, 'little') for d in dst)
    outraw = b"".join(o.to_bytes(eb, 'little') for o in out)
    inbuf = words + [0] * (32 - len(words) % 32 if len(words) % 32 else 0)
    inbuf = words + [0] * max(0, 32 - len(words))
    tail.append(f".buffer G{kk} .{bty} = {{ {h(int.from_bytes(dstraw[eb * i:eb * i + eb], 'little') for i in range(N))} }};\n"
                f".tensormap TM{kk} .{gty} G{kk} .dims {{ {N} }} .strides {{ 0 }} .box {{ {N} }} .swizzle 0 ;\n"
                f".buffer IN{kk} .u32 = {{ {h(inbuf)} }};\n.launch k{kk} <<< 1, 32 >>> (TM{kk}, IN{kk});\n"
                f".expect G{kk} .{bty} = {{ {h(int.from_bytes(outraw[eb * i:eb * i + eb], 'little') for i in range(N))} }};")
open('tests/tma-red.ptx', 'w').write("\n".join(L) + "\n" + "\n".join(tail) + "\n")

# ---- multicast with 16-bit / 32-bit masks and cta_group::2 signalling
def mc_test(name, qual, maskreg_ty, mask, cta2):
    dims = (64, 4); box = (64, 4)
    G = [random.randint(1, 60000) for _ in range(dims[0] * dims[1])]
    nb = box[0] * box[1] * 2
    img = []
    for v in G: img += [v & 255, v >> 8]
    words = [int.from_bytes(bytes(img[4 * i:4 * i + 4]), 'little') for i in range(nb // 4)]
    # mbarrier signalling: without cta_group::2 every destination CTA's own barrier gets nb bytes; with it, the barrier of the pair member
    # with the parity of the CTA holding mbar (CTA 0) gets nb bytes per destination
    dest = [r for r in range(2) if (mask >> r) & 1]
    Lk = [f"// GENERATED by scripts/gen_tma_red.py -- {name}", ".version 8.8\n.target sm_100a\n.address_size 64\n",
          f""".visible .entry k(.param .u64 ptm, .param .u64 po) .reqnctapercluster 2, 1, 1
{{
    .reg .b64 %tm, %o, %mb, %st, %t, %sa, %oo, %rb; .reg .b32 %tid, %cta, %buf32, %bar32, %x, %mk32, %nb; .reg .b16 %mk16; .reg .pred %q, %q0, %w;
    .shared .align 1024 .b8 buf[{(nb + 1023) // 1024 * 1024}];
    .shared .align 8 .b64 bar;
    ld.param.u64 %tm, [ptm]; ld.param.u64 %o, [po];
    mov.u32 %tid, %tid.x; mov.u32 %cta, %ctaid.x;
    setp.eq.u32 %q, %tid, 0;
    setp.eq.u32 %q0, %cta, 0;
    and.pred %q0, %q0, %q;
    mov.u64 %mb, bar; mov.u32 %bar32, bar; mov.u32 %buf32, buf;
    @%q mbarrier.init.shared.b64 [%mb], 1;
    fence.mbarrier_init.release.cluster;
    barrier.cluster.arrive.release.aligned;
    barrier.cluster.wait.acquire.aligned;"""]
    if cta2:
        # CTA 0's barrier receives the bytes of every destination; the other CTA does not wait on its barrier
        exp = nb * len(dest)
        Lk.append(f"    @%q0 mbarrier.arrive.expect_tx.shared.b64 %st, [%mb], {exp};")
    else:
        Lk.append(f"    @%q mbarrier.arrive.expect_tx.shared.b64 %st, [%mb], {nb};")
    Lk.append(f"    mov.b16 %mk16, {mask}; mov.b32 %mk32, {mask};")
    Lk.append(f"    @%q0 cp.async.bulk.tensor.2d.shared::cluster.global.tile.mbarrier::complete_tx::bytes.{qual} [%buf32], [%tm, {{0, 0}}], [%bar32], {'%mk32' if maskreg_ty == 32 else '%mk16'};")
    if cta2: Lk.append("    @%q0 mbarrier.try_wait.parity.shared.b64 %w, [%mb], 0;")      # only CTA 0's barrier is signalled
    else: Lk.append("    @%q mbarrier.try_wait.parity.shared.b64 %w, [%mb], 0;")
    Lk.append("    barrier.cluster.arrive.release.aligned;\n    barrier.cluster.wait.acquire.aligned;")
    Lk.append("    mul.wide.u32 %t, %tid, 4; mul.wide.u32 %rb, %cta, %d;".replace("%d", str(nb)) + "\n    add.u64 %oo, %o, %t; add.u64 %oo, %oo, %rb;\n    mov.u64 %sa, buf; add.u64 %sa, %sa, %t;")
    for i in range(0, nb // 4, 32): Lk.append(f"    ld.shared.b32 %x, [%sa+{4 * i}]; st.global.b32 [%oo+{4 * i}], %x;")
    Lk.append("    barrier.cluster.arrive.release.aligned;\n    barrier.cluster.wait.acquire.aligned;\n    ret;\n}\n")
    exp_out = []
    for r in range(2): exp_out += words if r in dest else [0] * len(words)
    tm = f".tensormap TM .f16 G .dims {{ {h(dims)} }} .strides {{ {dims[0] * 2} }} .box {{ {h(box)} }} .swizzle 0 ;"
    Lk.append(f".buffer G .u16 = {{ {h(G)} }};\n{tm}\n.buffer O .u32 [{2 * len(words)}];\n.launch k <<< 2, 32 >>> (TM, O);\n.expect O .u32 = {{ {h(exp_out)} }};")
    open(f'tests/tma-mc-{name}.ptx', 'w').write("\n".join(Lk) + "\n")
mc_test('16b', 'multicast::cluster', 16, 3, False)
mc_test('32b', 'multicast::cluster::32b', 32, 3, False)
mc_test('g2', 'multicast::cluster.cta_group::2', 16, 3, True)
mc_test('g2one', 'multicast::cluster.cta_group::2', 16, 2, True)
print("ok")
