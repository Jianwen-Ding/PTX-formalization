# ---------------------------------------------------------------- block scaling: UE5M3 (and the scale-factor TMEM layout of gen_tcgen05_bs.py)
def sfw(S, n, nb, sid, l, col):
    x = 32 * (col % 4) + l % 32
    return sum(S[x][j] << (8 * (sid + j - 4 * (col // 4))) for j in range(nb) if x < n and (sid + j) // 4 == col // 4)

def bs_case(kk, kind, vq, at, bt, N, K, blk, sty, sfa, sfb, en, lut=None, quals='', path=None, first='', directives='', target='sm_107f'):
    M = 128
    w = 4 if kind != 'kind::mxf8f6f4' else 8
    sf = {'ue8m0': ue8m0, 'ue5m3': ue5m3}[sty]
    sg = {'ue8m0': lambda: random.randint(122, 131), 'ue5m3': lambda: random.randint(0x60, 0x88)}[sty]
    nb = K // blk
    A = [[rand_float_bits(at) for _ in range(K)] for _ in range(M)]
    SA = [[sg() for _ in range(nb)] for _ in range(M)]
    SB = [[sg() for _ in range(nb)] for _ in range(N)]
    Din = [[rand_float_bits('f32') for _ in range(N)] for _ in range(M)]
    a_img, la, sa_ = build_tile(A, M, K, w, True, 1, 0, at if kind == 'kind::mxf8f6f4' else None)
    img = dict(a_img); descA = desc100(0, la, sa_, 1)
    off = (max(a_img) + 1 + 1023) // 1024 * 1024
    extra = []
    if lut is None:
        B = [[rand_float_bits(bt) for _ in range(K)] for _ in range(N)]
        b_img, lb, sb_ = build_tile(B, N, K, w, True, 1, off, bt if kind == 'kind::mxf8f6f4' else None)
        descB = desc100(off, lb, sb_, 1)
    else:
        B, b_img, descB, lw = lut_b(N, K, off, lut)
        extra.append((lut['col'], 4, lw))
    img.update(b_img)
    size, data = image(img)
    Dout = [[to_bits('f32', (fval('f32', Din[r][c]) if en else 0)
                     + sum(fval(at, A[r][k]) * fval(bt, B[c][k]) * sf(SA[r][k // blk]) * sf(SB[c][k // blk]) for k in range(K)))
             for c in range(N)] for r in range(M)]
    TC = {'e4m3': 0, 'e5m2': 1, 'e2m3': 3, 'e3m2': 4, 'e2m1': 1 if w == 4 else 5}
    STY = {'ue4m3': 0, 'ue8m0': 1, 'ue5m3': 2}
    idesc = (sfb << 4) | (TC[at] << 7) | (TC[bt] << 10) | ((N >> 3) << 17) | (STY[sty] << 23) | ((M >> 7) << 27) | (sfa << 29)
    if kind == 'kind::mxf8f6f4': idesc |= (1 if K == 64 else 0) << 31
    SAC, SBC = 300, 310
    extra += [(SAC, 8, [[sfw(SA, M, nb, sfa, l, col) for col in range(8)] for l in range(128)]),
              (SBC, 8, [[sfw(SB, N, nb, sfb, l, col) for col in range(8)] for l in range(128)])]
    setup = [f"mov.b64 %dB, {descB};", f"mov.b64 %dA, {descA};", f"mov.b32 %idesc, {idesc};", f"mov.u32 %r5, {SAC};",
             f"mov.u32 %r6, {SBC};", f"mov.u32 %r7, {lut['col'] if lut else 0};"]
    if lut is None:
        mma = f"tcgen05.mma.cta_group::1.{kind}.block_scale{vq}{quals} [%r3], %dA, %dB, %idesc, [%r5], [%r6], {en};"
    else:
        mma = f"tcgen05.mma.cta_group::1.{kind}.block_scale.decompress::lut::b{vq}{quals} [%r3], %dA, %dB, [%r7], %idesc, [%r5], [%r6], {en};"
    din = flat([[Din[u][c] for c in range(N)] for u in range(128)])
    dout = flat([[Dout[u][c] for c in range(N)] for u in range(128)])
    # mov.b32 %r5, 0 of program() comes after the setup: the scale columns go in %r8 / %r9 instead
    setup = [x.replace('%r5', '%r8').replace('%r6', '%r9') for x in setup]
    mma = mma.replace('[%r5]', '[%r8]').replace('[%r6]', '[%r9]')
    code = program(kk, data, N, din, None if path else dout, 'u32', extra, setup, [mma], directives, target=target, first=first)
    open(path or f'tests/tc-94-{kk}.ptx', 'w').write(code)

# ---------------------------------------------------------------- .decompress::lut::b
def lut_b(N, K, off, lut):
    """B (N x K, K = 64) from 3-bit indices into 8-byte tables; returns (B values, image, descriptor, TMEM words)"""
    assert K == 64
    tabs = [[random.choice(E4M3) for _ in range(8)] for _ in range(N // 8)]
    junk = [[random.getrandbits(8) for _ in range(8)] for _ in range(32)]          # the K[64:127] tables (Figure 282): not read
    half = lut['half']
    idx = [[random.randrange(8) for _ in range(128)] for _ in range(N)]             # a K = 128 block of indices per row
    B = [[tabs[n // 8][idx[n][64 * half + k]] for k in range(K)] for n in range(N)]
    rows = []
    for n in range(N):
        bits = sum(idx[n][k] << (3 * k) for k in range(128))                      # LSB first, 48 bytes
        rows.append([(bits >> (8 * i)) & 255 for i in range(48)])
    z = lut['z']
    b_img, lb, sb_ = build_tile(rows, N, 48, 8, True, z, off)
    descB = desc100(off, lb, sb_, z) | (half << 53)
    words = []
    for l in range(128):
        t = tabs[l] if l < N // 8 else [random.getrandbits(8) for _ in range(8)]
        j = junk[l % 32]
        words.append([sum(t[i] << (8 * i) for i in range(4)), sum(t[4 + i] << (8 * i) for i in range(4)),
                      sum(j[i] << (8 * i) for i in range(4)), sum(j[4 + i] << (8 * i) for i in range(4))])
    return B, b_img, descB, words

def lut_case(kk, N, negB, en, half, z, quals='', btype=0, path=None, first='', directives=''):
    M, K = 128, 64
    A = [[random.choice(E4M3) for _ in range(K)] for _ in range(M)]
    a_img, la, sa_ = build_tile(A, M, K, 8, True, 1, 0)
    off = (max(a_img) + 1 + 1023) // 1024 * 1024
    LC = 400
    B, b_img, descB, lw = lut_b(N, K, off, {'half': half, 'z': z, 'col': LC})
    img = dict(a_img); img.update(b_img)
    size, data = image(img)
    Din = [[rand_float_bits('f32') for _ in range(N)] for _ in range(M)]
    sb = -1 if negB else 1
    Dout = [[to_bits('f32', (fval('f32', Din[r][c]) if en else 0) + sum(fval('e4m3', A[r][k]) * sb * fval('e4m3', B[c][k]) for k in range(K)))
             for c in range(N)] for r in range(M)]
    idesc = (1 << 4) | (0 << 7) | (btype << 10) | (negB << 14) | ((N >> 3) << 17) | ((M >> 4) << 24) | (1 << 29)
    setup = [f"mov.b64 %dB, {descB};", f"mov.b64 %dA, {desc100(0, la, sa_, 1)};", f"mov.b32 %idesc, {idesc};", f"mov.u32 %r7, {LC};"]
    mma = f"tcgen05.mma.cta_group::1.kind::f8f6f4.decompress::lut::b{quals} [%r3], %dA, %dB, [%r7], %idesc, {{%r5, %r5, %r5, %r5}}, {en};"
    din = flat([[Din[u][c] for c in range(N)] for u in range(128)])
    dout = flat([[Dout[u][c] for c in range(N)] for u in range(128)])
    code = program(kk, data, N, din, None if path else dout, 'u32', [(LC, 4, lw)], setup, [mma], directives, first=first)
    open(path or f'tests/tc-94-{kk}.ptx', 'w').write(code)

