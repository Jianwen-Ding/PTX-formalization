#!/usr/bin/env python3
"""Generate tests/tma-rep-*.ptx: tensormap.replace of every field followed by a tile load, the .override::global_address / .override::global_dim_stride
operand forms, and the packed sub-byte element types (b4x16_p64, b6x16_p32).  usage: gen_tma_rep.py"""
import random
random.seed(17)
h = lambda xs: ", ".join(str(x) for x in xs)
SWZ = {'none': lambda c, l: c, '128a32': lambda c, l: 2 * ((c >> 1) ^ (l % 4)) + (c & 1)}
def swz_image(img, perm):
    out = [0] * len(img)
    for b in range(len(img)):
        line, c, off = b // 128, (b // 16) % 8, b % 16
        out[line * 128 + perm(c, line) * 16 + off] = img[b]
    return out
def words_of(b): return [sum(b[4 * i + j] << (8 * j) for j in range(4)) for i in range(len(b) // 4)]
HEAD = ".version 8.8\n.target sm_100a\n.address_size 64\n"
def dump(nb):
    L = ["    ld.param.u64 %o, [po];", "    mul.wide.u32 %t, %tid, 4;", "    mov.u64 %sa, buf; add.u64 %sa, %sa, %t; add.u64 %oo, %o, %t;"]
    for i in range(0, nb // 4, 32): L.append(f"    ld.shared.b32 %x, [%sa+{4 * i}]; st.global.b32 [%oo+{4 * i}], %x;")
    return L
def kernel(pre, tma, nb, params):
    return "\n".join([f"""// GENERATED by scripts/gen_tma_rep.py
{HEAD}
.visible .entry k({params})
{{
    .reg .b64 %tm, %o, %mb, %st, %t, %sa, %oo, %g2; .reg .b32 %tid, %buf32, %bar32, %x, %y, %z; .reg .b16 %u16; .reg .pred %q, %w;
    .shared .align 1024 .b8 buf[{(nb + 1023) // 1024 * 1024}];
    .shared .align 8 .b64 bar;
    ld.param.u64 %tm, [ptm]; ld.param.u64 %g2, [pg2];
    mov.u32 %tid, %tid.x;
    setp.eq.u32 %q, %tid, 0;
    mov.u64 %mb, bar; mov.u32 %bar32, bar; mov.u32 %buf32, buf;
    @%q mbarrier.init.shared.b64 [%mb], 1;"""] + pre + [f"""    bar.sync 0;
    @%q mbarrier.arrive.expect_tx.shared.b64 %st, [%mb], {nb};"""] + tma + ["""    @%q mbarrier.try_wait.parity.shared.b64 %w, [%mb], 0;
    bar.sync 0;"""] + dump(nb) + ["    ret;\n}\n"])
# ---- 1. replace every field
def t_replace():
    W0, H0 = 64, 8                                   # original tensor (never read after the global_address replace)
    G = [random.randint(1, 60000) for _ in range(W0 * H0)]
    ROW = 72                                          # G2: rows of 72 elements (144 bytes), only 64 of them are in the tensor
    G2 = [random.randint(1, 60000) for _ in range(ROW * 7)]
    dims = (64, 6); box = (64, 4); est1 = 2; coords = (0, 1)
    img = []
    # tiled mode: the element (traversal) stride reduces the elements of a dimension to ceil(boxDim / elementStride)
    # (PTX ISA 9.3 5.5.3.2, and 5.5.4.2: "does not impact the total number of elements ... unlike the tiled mode")
    for r in range(-(-box[1] // est1)):
        for c in range(box[0]):
            x, y = coords[0] + c, coords[1] + r * est1
            img += [0xc0, 0x7f] if (x >= dims[0] or y >= dims[1]) else [G2[y * ROW + x] & 255, G2[y * ROW + x] >> 8]
    sw = swz_image(img, SWZ['128a32'])
    pre = ["    @%q {\n" if False else ""]
    r = "global.b1024"
    pre = [f"    @%q tensormap.replace.tile.global_address.{r}.b64 [%tm], %g2;",
           f"    @%q tensormap.replace.tile.rank.{r}.b32 [%tm], 1;",
           f"    @%q tensormap.replace.tile.box_dim.{r}.b32 [%tm], 0, {box[0]};", f"    @%q tensormap.replace.tile.box_dim.{r}.b32 [%tm], 1, {box[1]};",
           f"    @%q tensormap.replace.tile.global_dim.{r}.b32 [%tm], 0, {dims[0]};", f"    @%q tensormap.replace.tile.global_dim.{r}.b32 [%tm], 1, {dims[1]};",
           f"    mov.u64 %t, {ROW * 2};", f"    @%q tensormap.replace.tile.global_stride.{r}.b64 [%tm], 0, %t;",
           f"    @%q tensormap.replace.tile.element_stride.{r}.b32 [%tm], 0, 1;", f"    @%q tensormap.replace.tile.element_stride.{r}.b32 [%tm], 1, {est1};",
           f"    @%q tensormap.replace.tile.elemtype.{r}.b32 [%tm], 10;", f"    @%q tensormap.replace.tile.interleave_layout.{r}.b32 [%tm], 0;",
           f"    @%q tensormap.replace.tile.swizzle_mode.{r}.b32 [%tm], 3;", f"    @%q tensormap.replace.tile.swizzle_atomicity.{r}.b32 [%tm], 1;",
           f"    @%q tensormap.replace.tile.fill_mode.{r}.b32 [%tm], 1;"]
    tma = [f"    @%q cp.async.bulk.tensor.2d.shared::cluster.global.tile.mbarrier::complete_tx::bytes [%buf32], [%tm, {{{h(coords)}}}], [%bar32];"]
    k = kernel(pre, tma, len(img), ".param .u64 ptm, .param .u64 pg2, .param .u64 po")
    k += (f".buffer G .u16 = {{ {h(G)} }};\n.buffer G2 .u16 = {{ {h(G2)} }};\n.tensormap TM .f16 G .dims {{ {W0}, {H0} }} .strides {{ {W0 * 2} }} .box {{ 8, 4 }} .swizzle 0 ;\n"
          f".buffer O .u32 [{len(img) // 4}];\n.launch k <<< 1, 32 >>> (TM, G2, O);\n.expect O .u32 = {{ {h(words_of(sw))} }};\n")
    open('tests/tma-rep-fields.ptx', 'w').write(k)
# ---- 2. override::global_address / global_dim_stride
def t_override(kind):
    W0, H0 = 16, 4
    G = [random.randint(1, 60000) for _ in range(W0 * H0)]
    ROW = 72
    G2 = [random.randint(1, 60000) for _ in range(ROW * 7)]
    sz = (40, 5); box = (16, 4); lower, upper = 9, 0         # stride = (lower + (upper << 32)) << 4 = 144 bytes
    img = []
    for r in range(box[1]):
        for c in range(box[0]):
            x, y = c, r
            if kind == 'addr': dims, stride = (W0, H0), W0 * 2
            else: dims, stride = sz, ((lower + (upper << 32)) << 4)
            base = G2
            if x >= dims[0] or y >= dims[1]: img += [0, 0]
            else:
                a = (y * stride + x * 2) // 2
                img += [base[a] & 255, base[a] >> 8]
    if kind == 'addr':
        q = "[%tm, %g2, {0, 0}]"
        tma = [f"    @%q cp.async.bulk.tensor.2d.shared::cluster.global.tile.mbarrier::complete_tx::bytes.override::global_address [%buf32], [%tm, %g2, {{0, 0}}], [%bar32];"]
        pre = []
    else:
        pre = [f"    mov.b16 %u16, {upper};", f"    mov.u32 %x, {sz[0]}; mov.u32 %y, {sz[1]};", f"    mov.u32 %z, {lower};"]
        tma = [f"    @%q cp.async.bulk.tensor.2d.shared::cluster.global.tile.mbarrier::complete_tx::bytes.override::global_address.override::global_dim_stride "
               f"[%buf32], [%tm, %g2, {{%x, %y}}, {{%z}}, %u16, {{0, 0}}], [%bar32];"]
    k = kernel(pre, tma, len(img), ".param .u64 ptm, .param .u64 pg2, .param .u64 po")
    k += (f".buffer G .u16 = {{ {h(G)} }};\n.buffer G2 .u16 = {{ {h(G2)} }};\n.tensormap TM .f16 G .dims {{ {W0}, {H0} }} .strides {{ {W0 * 2} }} .box {{ {h(box)} }} .swizzle 0 ;\n"
          f".buffer O .u32 [{len(img) // 4}];\n.launch k <<< 1, 32 >>> (TM, G2, O);\n.expect O .u32 = {{ {h(words_of(img))} }};\n")
    open(f'tests/tma-rep-ov{kind}.ptx', 'w').write(k)
# ---- 3. packed sub-byte types
def t_sub(code):
    nb_el = 4 if code == 14 else 6
    gb = 8 if code == 14 else 12
    rows, cols = 4, 32
    rowbytes = cols * nb_el // 8
    # "tensor stride in every dimension must be 32B aligned" for the padded sub-byte types (9.7.9.26.5.1): rows are
    # 32 bytes apart, the bytes after a row's data are not read
    pitch = 32
    G = [random.getrandbits(8) for _ in range(pitch * rows)]
    img = []
    for r in range(rows):
        for g in range(cols // 16):
            grp = G[r * pitch + g * gb: r * pitch + (g + 1) * gb]
            img += grp + [0] * (16 - gb)
    r = "global.b1024"
    pre = [f"    @%q tensormap.replace.tile.elemtype.{r}.b32 [%tm], {code};"]
    tma = ["    @%q cp.async.bulk.tensor.2d.shared::cluster.global.tile.mbarrier::complete_tx::bytes [%buf32], [%tm, {0, 0}], [%bar32];"]
    k = kernel(pre, tma, len(img), ".param .u64 ptm, .param .u64 pg2, .param .u64 po")
    k += (f".buffer G .u8 = {{ {h(G)} }};\n.buffer G2 .u8 [8];\n.tensormap TM .u8 G .dims {{ {cols}, {rows} }} .strides {{ {pitch} }} .box {{ {cols}, {rows} }} .swizzle 0 ;\n"
          f".buffer O .u32 [{len(img) // 4}];\n.launch k <<< 1, 32 >>> (TM, G2, O);\n.expect O .u32 = {{ {h(words_of(img))} }};\n")
    open(f'tests/tma-rep-sub{code}.ptx', 'w').write(k)
t_replace(); t_override('addr'); t_override('dimstride'); t_sub(14); t_sub(15)
print("ok")
