#!/usr/bin/env python3
"""Generate tests/carry.ptx: extended-precision (CC.CF) arithmetic, expected
values computed with Python big integers.   usage: gen_carry.py [N] [SEED]"""
import random, sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 12
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 3)
M = 0xFFFFFFFF
def rnd32():
    return random.choice([0, M, 0x80000000, 0x7FFFFFFF, 1]) if random.random() < 0.3 else random.getrandbits(32)
def s32(x): x &= M; return x - (1 << 32) if x >> 31 else x
A = [[rnd32() for _ in range(4)] for _ in range(N)]
B = [[rnd32() for _ in range(4)] for _ in range(N)]
C = [[rnd32() for _ in range(4)] for _ in range(N)]
def val(l): return sum(x << (32 * i) for i, x in enumerate(l))
def limbs(v, n): return [(v >> (32 * i)) & M for i in range(n)]
OUT = 24
exp = []
for i in range(N):
    a, b, c = A[i], B[i], C[i]
    o = []
    t = val(a) + val(b)                       # 128-bit add, 5th word = carry
    o += limbs(t & ((1 << 128) - 1), 4) + [t >> 128]
    t = val(a) - val(b)                       # 128-bit sub, 5th word = 0 - borrow
    o += limbs(t & ((1 << 128) - 1), 4) + [M if t < 0 else 0]
    o += limbs(val(a[:2]) * val(b[:2]), 4)    # 64x64 -> 128 via mad chain
    a64 = [val(a[:2]), val(a[2:])]; b64 = [val(b[:2]), val(b[2:])]
    r0 = a64[0] + b64[0]; r1 = a64[1] + b64[1] + (r0 >> 64)
    o += limbs(r0 & ((1 << 64) - 1), 2) + [(r1 >> 64)]   # (store r1 as two words below)
    o += limbs(r1 & ((1 << 64) - 1), 2) + [0]
    # signed mad chain
    def hi_s(x, y): return ((s32(x) * s32(y)) >> 32) & M
    def lo_s(x, y): return ((s32(x) * s32(y))) & M
    s0 = hi_s(a[0], b[0]) + c[0]; d0, cf = s0 & M, s0 >> 32
    s1 = lo_s(a[1], b[1]) + c[1] + cf; d1, cf1 = s1 & M, s1 >> 32
    s2 = hi_s(a[2], b[2]) + c[2] + cf1; d2 = s2 & M
    o += [d0, d1, d2, cf1]
    exp.append(o)
    assert len(o) == 24, len(o)

lim = lambda L: ", ".join(str(x) for row in L for x in row)
print("// GENERATED by scripts/gen_carry.py -- CC.CF extended-precision arithmetic.")
print("// Expected values come from Python big integers.")
print(""".version 8.0
.target sm_80
.address_size 64

.visible .entry carry(.param .u64 pa, .param .u64 pb, .param .u64 pc, .param .u64 po)
{
    .reg .b32 %r<64>;
    .reg .b64 %rd<24>;
    .reg .pred %p<2>;
    ld.param.u64 %rd1, [pa];
    ld.param.u64 %rd2, [pb];
    ld.param.u64 %rd3, [pc];
    ld.param.u64 %rd4, [po];
    mov.u32 %r0, %tid.x;
    mul.wide.u32 %rd5, %r0, 16;
    add.s64 %rd6, %rd1, %rd5;  add.s64 %rd7, %rd2, %rd5;  add.s64 %rd8, %rd3, %rd5;
    ld.global.v4.u32 {%r1, %r2, %r3, %r4}, [%rd6];        // a0..a3
    ld.global.v4.u32 {%r5, %r6, %r7, %r8}, [%rd7];        // b0..b3
    ld.global.v4.u32 {%r9, %r10, %r11, %r12}, [%rd8];     // c0..c3
    mul.wide.u32 %rd9, %r0, 96;
    add.s64 %rd10, %rd4, %rd9;                             // 24 words per thread

    // ---- 128-bit add with carry-out word
    add.cc.u32   %r20, %r1, %r5;
    addc.cc.u32  %r21, %r2, %r6;
    addc.cc.u32  %r22, %r3, %r7;
    addc.cc.u32  %r23, %r4, %r8;
    addc.u32     %r24, 0, 0;
    st.global.v4.u32 [%rd10], {%r20, %r21, %r22, %r23};
    st.global.u32 [%rd10+16], %r24;

    // ---- 128-bit sub; last word is 0 - borrow
    sub.cc.u32   %r20, %r1, %r5;
    subc.cc.u32  %r21, %r2, %r6;
    subc.cc.u32  %r22, %r3, %r7;
    subc.cc.u32  %r23, %r4, %r8;
    subc.u32     %r24, 0, 0;
    st.global.v4.u32 [%rd10+20], {%r20, %r21, %r22, %r23};
    st.global.u32 [%rd10+36], %r24;

    // ---- 64x64 -> 128 multiply with a mad.cc/madc chain
    mul.lo.u32   %r30, %r1, %r5;
    mul.hi.u32   %r31, %r1, %r5;
    mad.lo.cc.u32  %r31, %r2, %r5, %r31;
    madc.hi.u32    %r32, %r2, %r5, 0;
    mad.lo.cc.u32  %r31, %r1, %r6, %r31;
    madc.hi.cc.u32 %r32, %r1, %r6, %r32;
    madc.hi.u32    %r33, %r2, %r6, 0;
    mad.lo.cc.u32  %r32, %r2, %r6, %r32;
    addc.u32       %r33, %r33, 0;
    st.global.v4.u32 [%rd10+40], {%r30, %r31, %r32, %r33};

    // ---- two 64-bit limbs: (a0:a1) + (b0:b1) and (a2:a3) + (b2:b3) + carry
    mov.b64      %rd11, {%r1, %r2};
    mov.b64      %rd12, {%r5, %r6};
    mov.b64      %rd13, {%r3, %r4};
    mov.b64      %rd14, {%r7, %r8};
    add.cc.u64   %rd15, %rd11, %rd12;
    addc.cc.u64  %rd16, %rd13, %rd14;
    addc.u32     %r40, 0, 0;
    st.global.u64 [%rd10+56], %rd15;
    st.global.u32 [%rd10+64], %r40;
    mov.b64      {%r41, %r42}, %rd16;
    st.global.u32 [%rd10+68], %r41;
    st.global.u32 [%rd10+72], %r42;
    mov.u32      %r43, 0;
    st.global.u32 [%rd10+76], %r43;

    // ---- signed mad chain (hi of signed product), CF kept across addc
    mad.hi.cc.s32  %r50, %r1, %r5, %r9;
    madc.lo.cc.s32 %r51, %r2, %r6, %r10;
    addc.u32       %r53, 0, 0;                  // carry out of the previous madc (no clobber)
    madc.hi.s32    %r52, %r3, %r7, %r11;
    st.global.u32 [%rd10+80], %r50;
    st.global.u32 [%rd10+84], %r51;
    st.global.u32 [%rd10+88], %r52;
    st.global.u32 [%rd10+92], %r53;
    ret;
}
""")
print(f".buffer A .u32 = {{ {lim(A)} }};")
print(f".buffer B .u32 = {{ {lim(B)} }};")
print(f".buffer C .u32 = {{ {lim(C)} }};")
print(f".buffer O .u32 [{N * OUT}];")
print(f".launch carry <<< 1, {N} >>> (A, B, C, O);")
print(f".expect O .u32 = {{ {lim(exp)} }};")
