#!/usr/bin/env python3
"""Generate tests/ldm2-*.ptx: ldmatrix .m16n16 / .m8n16 (8-bit data, 6/4-bit expansion, s8.s4) and stmatrix .m16n8 (8-bit) against direct models
of the fragment layouts documented in semantics/ptx-exec-ldm.k.  usage: gen_ldm2.py"""
import random
random.seed(77)
h = lambda xs: ", ".join(str(x) for x in xs)
HDR = ".version 8.6\n.target sm_100a\n.address_size 64\n"
def el(fmt, row, c):          # row: list of 16 bytes
    big = sum(b << (8 * i) for i, b in enumerate(row))
    if fmt == 'b8': return row[c]
    if fmt == 'b6': return (big >> (6 * c)) & 63
    if fmt == 'b4': return ((big >> (4 * c)) & 15) << 2
    if fmt == 's4':
        v = (big >> (4 * c)) & 15
        return (v | 0xF0) if v & 8 else v
def ld_case(kk, shape, num, fmt, qual):
    rows = [[random.getrandbits(8) for _ in range(16)] for _ in range(32)]
    nrow = 16 if shape == 'm16n16' else 8
    out = [[] for _ in range(32)]
    for t in range(32):
        g, tig = t // 4, t % 4
        for i in range(num):
            R = rows[nrow * i: nrow * (i + 1)]
            if shape == 'm8n16':
                out[t].append(sum(el(fmt, R[g], 4 * tig + b) << (8 * b) for b in range(4)))
            else:
                for col in (g, g + 8):
                    out[t].append(sum(el(fmt, R[4 * tig + b], col) << (8 * b) for b in range(4)))
    nreg = len(out[0])
    img = [b for r in rows for b in r]
    regs = ", ".join(f"%d{i}" for i in range(nreg))
    L = [f"// GENERATED by scripts/gen_ldm2.py", HDR,
         f".visible .entry k{kk}(.param .u64 pin, .param .u64 po)\n{{\n    .reg .b32 %r<8>, %d<{nreg}>; .reg .b64 %rd<8>; .shared .align 16 .b8 buf[512];",
         "    mov.u32 %r0, %tid.x;",
         "    ld.param.u64 %rd0, [pin]; mul.wide.u32 %rd1, %r0, 16; add.u64 %rd0, %rd0, %rd1;",
         "    ld.global.b32 %r1, [%rd0]; ld.global.b32 %r2, [%rd0+4]; ld.global.b32 %r3, [%rd0+8]; ld.global.b32 %r4, [%rd0+12];",
         "    mov.u64 %rd2, buf; add.u64 %rd2, %rd2, %rd1;",
         "    st.shared.b32 [%rd2], %r1; st.shared.b32 [%rd2+4], %r2; st.shared.b32 [%rd2+8], %r3; st.shared.b32 [%rd2+12], %r4;",
         "    bar.sync 0;",
         f"    ldmatrix.sync.aligned.{shape}.x{num}{qual} {{{regs}}}, [%rd2];",
         f"    ld.param.u64 %rd3, [po]; mul.wide.u32 %rd4, %r0, {4 * nreg}; add.u64 %rd3, %rd3, %rd4;"]
    for i in range(nreg): L.append(f"    st.global.b32 [%rd3+{4 * i}], %d{i};")
    L.append("    ret;\n}\n")
    L.append(f".buffer IN .u8 = {{ {h(img)} }};\n.buffer O .u32 [{32 * nreg}];\n.launch k{kk} <<< 1, 32 >>> (IN, O);\n.expect O .u32 = {{ {h([x for r in out for x in r])} }};")
    open(f'tests/ldm2-{kk}.ptx', 'w').write("\n".join(L) + "\n")
cases = [('m16n16', 1, 'b8', '.trans.shared.b8'), ('m16n16', 2, 'b6', '.trans.shared.b8x16.b6x16_p32'), ('m16n16', 1, 'b4', '.trans.shared.b8x16.b4x16_p64'),
         ('m8n16', 2, 'b6', '.shared.b8x16.b6x16_p32'), ('m8n16', 1, 'b4', '.shared.b8x16.b4x16_p64'), ('m8n16', 4, 's4', '.shared::cta.s8.s4')]
for kk, c in enumerate(cases): ld_case(kk, *c)
# stmatrix.m16n8.b8
def st_case(kk, num):
    regs = [[random.getrandbits(32) for _ in range(num)] for _ in range(32)]
    mem = [0] * 512
    for i in range(num):
        for n in range(8):
            for m in range(16):
                g, j = m % 8, m // 8
                lane = 4 * g + n // 2
                mem[128 * i + 16 * n + m] = (regs[lane][i] >> (8 * (2 * j + n % 2))) & 255
    rn = ", ".join(f"%v{i}" for i in range(num))
    L = [f"// GENERATED by scripts/gen_ldm2.py", HDR,
         f".visible .entry k{kk}(.param .u64 pin, .param .u64 po)\n{{\n    .reg .b32 %r<8>, %v<{num}>, %w; .reg .b64 %rd<8>; .shared .align 16 .b8 buf[512];",
         "    mov.u32 %r0, %tid.x;",
         f"    ld.param.u64 %rd0, [pin]; mul.wide.u32 %rd1, %r0, {4 * num}; add.u64 %rd0, %rd0, %rd1;"]
    for i in range(num): L.append(f"    ld.global.b32 %v{i}, [%rd0+{4 * i}];")
    L += ["    mul.wide.u32 %rd1, %r0, 16; mov.u64 %rd2, buf; add.u64 %rd2, %rd2, %rd1;",
          f"    stmatrix.sync.aligned.m16n8.x{num}.trans.shared.b8 [%rd2], {{{rn}}};",
          "    bar.sync 0;",
          "    ld.param.u64 %rd3, [po]; mul.wide.u32 %rd4, %r0, 16; add.u64 %rd3, %rd3, %rd4;"]
    L.append("    ld.shared.b32 %w, [%rd2]; st.global.b32 [%rd3], %w; ld.shared.b32 %w, [%rd2+4]; st.global.b32 [%rd3+4], %w;")
    L.append("    ld.shared.b32 %w, [%rd2+8]; st.global.b32 [%rd3+8], %w; ld.shared.b32 %w, [%rd2+12]; st.global.b32 [%rd3+12], %w;")
    L.append("    ret;\n}\n")
    exp = [mem[4 * i] | (mem[4 * i + 1] << 8) | (mem[4 * i + 2] << 16) | (mem[4 * i + 3] << 24) for i in range(32 * 4)]
    flat = [x for r in regs for x in r]
    L.append(f".buffer IN .u32 = {{ {h(flat)} }};\n.buffer O .u32 [128];\n.launch k{kk} <<< 1, 32 >>> (IN, O);\n.expect O .u32 @ 0 = {{ {h(exp[:32 * num][:32])} }};" if False else
             f".buffer IN .u32 = {{ {h(flat)} }};\n.buffer O .u32 [128];\n.launch k{kk} <<< 1, 32 >>> (IN, O);\n.expect O .u32 = {{ {h(exp)} }};")
    open(f'tests/ldm2-st{kk}.ptx', 'w').write("\n".join(L) + "\n")
for kk, num in enumerate((1, 2, 4)): st_case(kk, num)
