#!/usr/bin/env python3
"""Generate ptx_isa_table.sail (isaRows) from the K table semantics/ptx-isa-table.k."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(HERE, "..", "..", "semantics", "ptx-isa-table.k")
rows = []
for line in open(src):
    m = re.match(r'\s*rule isaRows\("([^"]*)"\) => (.*)$', line)
    if not m:
        continue
    items = re.findall(r'isaRow\("([^"]*)", (\d+), (\d+), (true|false)\)', m.group(2))
    rows.append((m.group(1), items))
out = ["/* GENERATED by gen_isa_table.py from semantics/ptx-isa-table.k -- do not edit.",
       " * isaRows(op): (qualifiers joined by +, min PTX version x10, min sm, arch-specific?) */",
       "val isaRows : string -> list((string, int, int, bool))",
       "function isaRows(op) = match op {"]
for op, items in rows:
    out.append('  "%s" => [|%s|],' % (op, ", ".join('("%s", %s, %s, %s)' % it for it in items)))
out.append("  _ => [||]")
out.append("}")
open(os.path.join(HERE, "ptx_isa_table.sail"), "w").write("\n".join(out) + "\n")
