#!/usr/bin/env python3
"""Translate a tests/memmodel/*.litmus test into a PTX kernel for the K semantics in relaxed memory mode.

Each litmus thread becomes one thread of a CTA (threads that share `cta=` share a CTA); `exists` (a conjunction of
register / location equalities) becomes the `.expect` lines, so that exit code 0 of
    krun -d build/ptx-search-kompiled out.ptx --search --pattern '<exit-code> X:Int </exit-code>'
means "the outcome of interest is reachable".  Tests that use virtual aliases, proxies, barriers, disjunctions or
inequalities are not translated.
"""
import re, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
import ptxmm


def translatable(t):
    if t['alias']:
        return False
    ex = t['exists'] or ''
    if '||' in ex or '!=' in ex:
        return False
    for th in t['threads']:
        for s in th['ins']:
            if 'bar.' in s or 'proxy' in s or '@proxy' in s:
                return False
    return True


def reg(r):
    return '%' + r


def operand(x):
    return x if re.fullmatch(r'-?\d+', x) else reg(x)


def emit(d, lines, pcount):
    op = d['op']
    guard = ''
    if d['cond'] is not None:
        p = f"%q{pcount[0]}"; pcount[0] += 1
        lines.append(f"    setp.eq.u32 {p}, {reg(d['cond'][0])}, {d['cond'][1]};")
        guard = f"@{p} "
    sem = '' if d['sem'] == 'weak' else '.' + d['sem']
    sc = '' if d['scope'] is None or d['sem'] == 'weak' else '.' + d['scope']
    if op == 'st':
        lines.append(f"    {guard}st{sem}{sc}.global.u32 [{d['args'][0]}], {operand(d['args'][1])};")
    elif op == 'ld':
        lines.append(f"    {guard}ld{sem}{sc}.global.u32 {reg(d['dst'])}, [{d['args'][0]}];")
    elif op in ('atom', 'red'):
        a = d['args']
        t = 'b32' if d['aop'] in ('cas', 'exch') else 'u32'
        extra = ''.join(', ' + operand(x) for x in a[1:])
        dst = reg(d['dst']) + ', ' if op == 'atom' else ''
        if op == 'atom' and d['dst'] is None:
            dst = '_, '
        lines.append(f"    {guard}{op}{sem}{sc}.global.{d['aop']}.{t} {dst}[{a[0]}]{extra};")
    elif op == 'fence':
        k = d['fkind']
        lines.append(f"    {guard}fence.{k}.{d['scope']};")
    else:
        raise ValueError(op)


def translate(t):
    ctas = sorted({th['cta'] for th in t['threads']})
    perc = {c: [i for i, th in enumerate(t['threads']) if th['cta'] == c] for c in ctas}
    nthr = max(len(v) for v in perc.values())
    locs = sorted({d for th in t['threads'] for s in th['ins'] for d in re.findall(r'\b([a-z]\w*)\b', '') })
    # locations and registers
    locs = []
    regs = []
    for th in t['threads']:
        for s in th['ins']:
            d = ptxmm.parse_ins(s)
            if d['op'] in ('ld', 'st', 'atom', 'red') and d['args'][0] not in locs:
                locs.append(d['args'][0])
            if d['dst'] and d['dst'] not in regs:
                regs.append(d['dst'])
    for l in t['init']:
        if l not in locs: locs.append(l)
    out = [f"// GENERATED by scripts/litmus2ptx.py from tests/memmodel: {t['name']} -- {t['desc']}",
           ".version 8.6", ".target sm_90", ".address_size 64", ""]
    for l in locs:
        out.append(f".global .align 4 .u32 {l} = {t['init'].get(l, 0)};")
    for r in regs:
        out.append(f".global .align 4 .u32 res_{r};")
    out.append("")
    allregs = ' '.join(f"%{r}," for r in regs).rstrip(',')
    out.append(".visible .entry k()\n{")
    out.append(f"    .reg .b32 %cta, %tid{', ' + allregs if regs else ''}; .reg .pred %pc, %pt;")
    for i in range(8): out.append(f"    .reg .pred %q{i};")
    out.append("    mov.u32 %cta, %ctaid.x;\n    mov.u32 %tid, %tid.x;")
    for c in ctas:
        for k, ti in enumerate(perc[c]):
            out.append(f"    setp.eq.u32 %pc, %cta, {ctas.index(c)};\n    setp.eq.u32 %pt, %tid, {k};\n    and.pred %pc, %pc, %pt;\n    @%pc bra T{ti};")
    out.append("    ret;")
    for ti, th in enumerate(t['threads']):
        out.append(f"T{ti}:")
        lines = []
        pc = [0]
        regs_t = []
        for s in th['ins']:
            d = ptxmm.parse_ins(s)
            emit(d, lines, pc)
            if d['dst'] and d['dst'] not in regs_t: regs_t.append(d['dst'])
        out.extend(lines)
        for r in regs_t:
            out.append(f"    st.global.u32 [res_{r}], %{r};")
        out.append("    ret;")
    out.append("}\n")
    out.append(".memmodel relaxed ;")
    out.append(f".launch k <<< {len(ctas)}, {nthr} >>> ();")
    for c in re.split(r'\s*&&\s*', (t['exists'] or '').strip()):
        if not c: continue
        m = re.fullmatch(r'(\[?\w+\]?)\s*==\s*(-?\d+)', c)
        name, v = m.group(1), m.group(2)
        if name.startswith('['):
            out.append(f".expect {name[1:-1]} .u32 = {{ {v} }};")
        else:
            out.append(f".expect res_{name} .u32 = {{ {v} }};")
    return "\n".join(out) + "\n"


if __name__ == '__main__':
    for f in sys.argv[1:]:
        for t in ptxmm.parse(open(f).read()):
            if translatable(t):
                print(translate(t))
