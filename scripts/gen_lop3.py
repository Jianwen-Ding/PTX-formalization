#!/usr/bin/env python3
"""Generate tests/lop3-shf.ptx: all 256 lop3 truth tables on random inputs, the
predicate-output forms, and funnel shifts, against bit-by-bit Python models.
usage: gen_lop3.py [THREADS] [SEED]"""
import random, sys
T = int(sys.argv[1]) if len(sys.argv) > 1 else 8
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 9)
M32 = (1 << 32) - 1
r32 = lambda: random.choice([0, M32, 0xAAAAAAAA, 0x55555555, 0xF0F0F0F0]) if random.random() < .3 else random.getrandbits(32)
A = [r32() for _ in range(T)]; B = [r32() for _ in range(T)]; C = [r32() for _ in range(T)]
S = [random.choice([0, 1, 31, 32, 33, 44, 63, 64, 255]) if random.random() < .5 else random.randint(0, 70) for _ in range(T)]
QP = [random.getrandbits(1) for _ in range(T)]

def lop3(a, b, c, lut):
    d = 0
    for i in range(32):
        idx = (((a >> i) & 1) << 2) | (((b >> i) & 1) << 1) | ((c >> i) & 1)
        d |= ((lut >> idx) & 1) << i
    return d
def shf(left, clamp, a, b, c):
    n = min(c, 32) if clamp else c & 31
    v = (b << 32) | a
    return ((((v << n) & ((1 << 64) - 1)) >> 32) if left else (v >> n)) & M32

print("// GENERATED by scripts/gen_lop3.py")
print(".version 8.0\n.target sm_80\n.address_size 64\n")
nl = 256
print(f""".visible .entry kl(.param .u64 pa, .param .u64 pb, .param .u64 pc, .param .u64 po)
{{
    .reg .b32 %r<16>; .reg .b64 %rd<8>; .reg .pred %p<4>;
    mov.u32 %r0, %tid.x;
    mul.wide.u32 %rd1, %r0, 4;
    ld.param.u64 %rd2, [pa]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r1, [%rd2];
    ld.param.u64 %rd2, [pb]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r2, [%rd2];
    ld.param.u64 %rd2, [pc]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r3, [%rd2];
    ld.param.u64 %rd3, [po];
    mul.wide.u32 %rd4, %r0, {nl * 4};
    add.s64 %rd3, %rd3, %rd4;""")
for lut in range(nl):
    print(f"    lop3.b32 %r4, %r1, %r2, %r3, {lut};  st.global.u32 [%rd3+{lut * 4}], %r4;")
print("    ret;\n}\n")
exp = [lop3(A[t], B[t], C[t], l) for t in range(T) for l in range(nl)]
lst = lambda v: ", ".join(map(str, v))
print(f".buffer LA .u32 = {{ {lst(A)} }};\n.buffer LB .u32 = {{ {lst(B)} }};\n.buffer LC .u32 = {{ {lst(C)} }};")
print(f".buffer LO .u32 [{T * nl}];\n.launch kl <<< 1, {T} >>> (LA, LB, LC, LO);\n.expect LO .u32 = {{ {lst(exp)} }};")

# predicate forms + funnel shifts
print("""
.visible .entry kp(.param .u64 pa, .param .u64 pb, .param .u64 pc, .param .u64 ps, .param .u64 pq, .param .u64 po)
{
    .reg .b32 %r<24>; .reg .b64 %rd<8>; .reg .pred %p<8>;
    mov.u32 %r0, %tid.x;
    mul.wide.u32 %rd1, %r0, 4;
    ld.param.u64 %rd2, [pa]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r1, [%rd2];
    ld.param.u64 %rd2, [pb]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r2, [%rd2];
    ld.param.u64 %rd2, [pc]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r3, [%rd2];
    ld.param.u64 %rd2, [ps]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r5, [%rd2];
    ld.param.u64 %rd2, [pq]; add.s64 %rd2, %rd2, %rd1; ld.global.u32 %r6, [%rd2];
    setp.ne.u32 %p1, %r6, 0;
    ld.param.u64 %rd3, [po];
    mul.wide.u32 %rd4, %r0, 28; add.s64 %rd3, %rd3, %rd4;
    lop3.and.b32 %r4|%p2, %r1, %r2, %r3, 0xE8, %p1;      // majority, p = (d != 0) && q
    selp.u32 %r7, 1, 0, %p2;
    lop3.or.b32 %r8|%p3, %r1, %r2, %r3, 0x96, %p1;       // xor3, p = (d != 0) || q
    selp.u32 %r9, 1, 0, %p3;
    st.global.u32 [%rd3], %r4;  st.global.u32 [%rd3+4], %r7;  st.global.u32 [%rd3+8], %r8; st.global.u32 [%rd3+12], %r9;
    shf.l.wrap.b32  %r10, %r1, %r2, %r5;
    shf.l.clamp.b32 %r11, %r1, %r2, %r5;
    shf.r.wrap.b32  %r12, %r1, %r2, %r5;
    shf.r.clamp.b32 %r13, %r1, %r2, %r5;
    st.global.u32 [%rd3+16], %r10; st.global.u32 [%rd3+20], %r11; st.global.u32 [%rd3+24], %r12;
    ret;
}
""")
# one extra word per thread for shf.r.clamp -> separate kernel output would be cleaner; keep 7 words and test r.clamp separately
exp2 = []
for t in range(T):
    d1 = lop3(A[t], B[t], C[t], 0xE8); d2 = lop3(A[t], B[t], C[t], 0x96)
    exp2 += [d1, int(d1 != 0 and QP[t] != 0), d2, int(d2 != 0 or QP[t] != 0),
             shf(True, False, A[t], B[t], S[t]), shf(True, True, A[t], B[t], S[t]), shf(False, False, A[t], B[t], S[t])]
print(f".buffer PS .u32 = {{ {lst(S)} }};\n.buffer PQ .u32 = {{ {lst(QP)} }};")
print(f".buffer PO .u32 [{T * 7}];\n.launch kp <<< 1, {T} >>> (LA, LB, LC, PS, PQ, PO);\n.expect PO .u32 = {{ {lst(exp2)} }};")
