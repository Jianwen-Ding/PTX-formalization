#!/usr/bin/env python3
"""Generate a PTX test from Berkeley TestFloat vectors (trusted IEEE-754 reference).

usage: gen_testfloat.py TESTFLOAT_GEN [LEVEL] [MAXN] [TF_MODE] [PTX_MODE] > tests/testfloat.ptx
  TF_MODE: near_even (default), minMag, min, max, near_maxMag  <->  PTX_MODE rn, rz, rm, rp, rna

TestFloat's testfloat_gen emits operands, the result of Berkeley SoftFloat and
exception flags.  Rounding mode is selected with TF_MODE / PTX_MODE.  NaN results are mapped to PTX's
canonical NaN, since NaN payload propagation is not specified by PTX.
"""
import subprocess, sys

gen = sys.argv[1]
level = sys.argv[2] if len(sys.argv) > 2 else "1"
maxn = int(sys.argv[3]) if len(sys.argv) > 3 else 150
tfmode = sys.argv[4] if len(sys.argv) > 4 else "near_even"
ptxmode = sys.argv[5] if len(sys.argv) > 5 else "rn"

def vectors(fn, nargs, w):
    out = subprocess.run([gen, "-level", level, f"-r{tfmode}", fn],
                         capture_output=True, text=True, check=True).stdout.splitlines()
    step = max(1, len(out) // maxn)
    rows = []
    for line in out[::step][:maxn]:
        f = line.split()
        args = [int(x, 16) for x in f[:nargs]]
        res = int(f[nargs], 16)
        isnan = ((res >> (w - 1 - (8 if w == 32 else 11))) & 1) is not None and \
            ((res >> (23 if w == 32 else 52)) & (0xFF if w == 32 else 0x7FF)) == (0xFF if w == 32 else 0x7FF) and \
            (res & ((1 << (23 if w == 32 else 52)) - 1)) != 0
        if isnan:
            res = (1 << (w - 1)) - 1
        rows.append((args, res))
    return rows

OPS = [  # name, testfloat fn, nargs, width, ptx opcode, type
    ("ADD32", "f32_add", 2, 32, f"add.{ptxmode}.f32", "f32"),
    ("SUB32", "f32_sub", 2, 32, f"sub.{ptxmode}.f32", "f32"),
    ("MUL32", "f32_mul", 2, 32, f"mul.{ptxmode}.f32", "f32"),
    ("DIV32", "f32_div", 2, 32, f"div.{ptxmode}.f32", "f32"),
    ("SQRT32", "f32_sqrt", 1, 32, f"sqrt.{ptxmode}.f32", "f32"),
    ("FMA32", "f32_mulAdd", 3, 32, f"fma.{ptxmode}.f32", "f32"),
    ("ADD64", "f64_add", 2, 64, f"add.{ptxmode}.f64", "f64"),
    ("SUB64", "f64_sub", 2, 64, f"sub.{ptxmode}.f64", "f64"),
    ("MUL64", "f64_mul", 2, 64, f"mul.{ptxmode}.f64", "f64"),
    ("DIV64", "f64_div", 2, 64, f"div.{ptxmode}.f64", "f64"),
    ("SQRT64", "f64_sqrt", 1, 64, f"sqrt.{ptxmode}.f64", "f64"),
    ("FMA64", "f64_mulAdd", 3, 64, f"fma.{ptxmode}.f64", "f64"),
]

def h(v, w): return ("0f%08X" if w == 32 else "0d%016X") % v
def lst(vals, w): return "{ " + ", ".join(h(v, w) for v in vals) + " }"

data = {}
for name, fn, nargs, w, opc, ty in OPS:
    rows = vectors(fn, nargs, w)
    n = len(rows)
    # testfloat_gen operand order for mulAdd is (a, b, c) with result a*b+c
    data[name] = (rows, n, nargs, w, opc, ty)

params = []
body = []
bufs = []
launches = []
expects = []
reg = 0
for name, (rows, n, nargs, w, opc, ty) in data.items():
    inreg = "%f" if w == 32 else "%fd"
    sz = w // 8
    names = [f"{name}_{c}" for c in "ABC"[:nargs]] + [f"{name}_R"]
    for i, nm in enumerate(names):
        bufs.append((nm, w, ty, [r[0][i] if i < nargs else r[1] for r in rows] if i < nargs else None))
    params += [f".param .u64 p_{nm}" for nm in names]
    loads = []
    for i, nm in enumerate(names[:nargs]):
        loads.append(f"    ld.param.u64 %rd1, [p_{nm}]; add.s64 %rd1, %rd1, %rd{40}; ld.global.{ty} {inreg}{i+1}, [%rd1];")
    body.append("\n".join(loads))
    args = ", ".join(f"{inreg}{i+1}" for i in range(nargs))
    body.append(f"    {opc} {inreg}9, {args};")
    body.append(f"    ld.param.u64 %rd2, [p_{names[-1]}]; add.s64 %rd2, %rd2, %rd{41 if sz == 8 else 40}; st.global.{ty} [%rd2], {inreg}9;")
    launches.append((name, names, n, w))
    expects.append((names[-1], ty, [r[1] for r in rows], w))

# one kernel per op keeps register pressure and thread counts simple
print("// GENERATED by scripts/gen_testfloat.py from Berkeley TestFloat 3e vectors.")
print("// Reference results: Berkeley SoftFloat, rounding mode "+tfmode+".")
print(".version 8.0\n.target sm_80\n.address_size 64\n")
for name, (rows, n, nargs, w, opc, ty) in data.items():
    inreg = "%f" if w == 32 else "%fd"
    sz = w // 8
    names = [f"{name}_{c}" for c in "ABC"[:nargs]] + [f"{name}_R"]
    ps = ",\n    ".join(f".param .u64 p{i}" for i in range(len(names)))
    print(f".visible .entry k_{name}(\n    {ps})\n{{")
    print("    .reg .b32 %r<2>;\n    .reg .f32 %f<10>;\n    .reg .f64 %fd<10>;\n    .reg .b64 %rd<8>;")
    print("    mov.u32 %r1, %tid.x;")
    print(f"    mul.wide.u32 %rd0, %r1, {sz};")
    for i in range(nargs):
        print(f"    ld.param.u64 %rd1, [p{i}]; add.s64 %rd1, %rd1, %rd0; ld.global.{ty} {inreg}{i+1}, [%rd1];")
    print(f"    {opc} {inreg}9, " + ", ".join(f"{inreg}{i+1}" for i in range(nargs)) + ";")
    print(f"    ld.param.u64 %rd2, [p{nargs}]; add.s64 %rd2, %rd2, %rd0; st.global.{ty} [%rd2], {inreg}9;")
    print("    ret;\n}\n")
for name, (rows, n, nargs, w, opc, ty) in data.items():
    names = [f"{name}_{c}" for c in "ABC"[:nargs]] + [f"{name}_R"]
    for i in range(nargs):
        print(f".buffer {names[i]} .{ty} = {lst([r[0][i] for r in rows], w)};")
    print(f".buffer {names[-1]} .{ty} [{n}];")
    print(f".launch k_{name} <<< 1, {n} >>> ({', '.join(names)});")
    print(f".expect {names[-1]} .{ty} = {lst([r[1] for r in rows], w)};")
