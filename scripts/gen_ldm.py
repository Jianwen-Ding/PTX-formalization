#!/usr/bin/env python3
"""Generate tests/ldm.ptx: ldmatrix / stmatrix / movmatrix against a matrix-level model."""
import random, struct
random.seed(11)
def u16s(vals): return b''.join(struct.pack('<H', v) for v in vals)
def regs_from(mats, trans):
    """mats: list of 8x8; returns out[lane][i] = 32-bit register"""
    out = []
    for lane in range(32):
        g, t = lane // 4, lane % 4
        row = []
        for M in mats:
            lo, hi = (M[2 * t][g], M[2 * t + 1][g]) if trans else (M[g][2 * t], M[g][2 * t + 1])
            row.append(lo | (hi << 16))
        out.append(row)
    return out
def mats_from(regs, n, trans):
    ms = [[[0] * 8 for _ in range(8)] for _ in range(n)]
    for lane in range(32):
        g, t = lane // 4, lane % 4
        for i in range(n):
            lo, hi = regs[lane][i] & 0xffff, regs[lane][i] >> 16
            if trans: ms[i][2 * t][g], ms[i][2 * t + 1][g] = lo, hi
            else: ms[i][g][2 * t], ms[i][g][2 * t + 1] = lo, hi
    return ms
h = lambda b: ", ".join(str(x) for x in b)
HDR = ["// GENERATED by scripts/gen_ldm.py -- ldmatrix/stmatrix/movmatrix vs. a matrix-level model",
       ".version 8.0\n.target sm_90\n.address_size 64\n"]
out = list(HDR); tail = []
K = 0
def flush():
    global out, tail
    open(f'tests/ldm-{K}.ptx', 'w').write("\n".join(out) + "\n" + "\n".join(tail) + "\n")
    out = list(HDR); tail = []
for n in (1, 2, 4):
    for trans in (False, True):
        for store_trans in (False, True):
            mats = [[[random.randrange(65536) for _ in range(8)] for _ in range(8)] for _ in range(n)]
            inb = b''.join(u16s([x for r in M for x in r]) for M in mats)
            regs = regs_from(mats, trans)
            ldexp = b''.join(struct.pack('<I', regs[l][i]) for l in range(32) for i in range(n))
            # stmatrix of the loaded registers back with store_trans
            back = mats_from(regs, n, store_trans)
            stexp = b''.join(u16s([x for r in M for x in r]) for M in back)
            rl = ", ".join(f"%x{i}" for i in range(n))
            tr = ".trans" if trans else ""
            st = ".trans" if store_trans else ""
            nbytes = 128 * n
            out.append(f""".visible .entry k{K}(.param .u64 pi, .param .u64 pl, .param .u64 ps)
{{
    .reg .b64 %pi, %pl, %ps, %a, %t, %sa, %sb; .reg .b32 %tid, %v<4>, %x<4>;
    .shared .align 16 .b8 buf[1024];
    ld.param.u64 %pi, [pi]; ld.param.u64 %pl, [pl]; ld.param.u64 %ps, [ps];
    mov.u32 %tid, %tid.x;
    mul.wide.u32 %t, %tid, 16;
    // copy the input into shared memory, 16 bytes per lane
    add.u64 %a, %pi, %t; mov.u64 %sa, buf; add.u64 %sa, %sa, %t;
    ld.global.b32 %v0, [%a]; ld.global.b32 %v1, [%a+4]; ld.global.b32 %v2, [%a+8]; ld.global.b32 %v3, [%a+12];
    st.shared.b32 [%sa], %v0; st.shared.b32 [%sa+4], %v1; st.shared.b32 [%sa+8], %v2; st.shared.b32 [%sa+12], %v3;
    bar.sync 0;
    ldmatrix.sync.aligned.m8n8.x{n}{tr}.shared.b16 {{{rl}}}, [%sa];
    mul.wide.u32 %t, %tid, {4 * n};
    add.u64 %a, %pl, %t;
""" + "".join(f"    st.global.b32 [%a+{4 * i}], %x{i};\n" for i in range(n)) + f"""    mul.wide.u32 %t, %tid, 16;
    mov.u64 %sb, buf; add.u64 %sb, %sb, 512; add.u64 %sb, %sb, %t;
    stmatrix.sync.aligned.m8n8.x{n}{st}.shared.b16 [%sb], {{{rl}}};
    bar.sync 0;
    ld.shared.b32 %v0, [%sb]; ld.shared.b32 %v1, [%sb+4]; ld.shared.b32 %v2, [%sb+8]; ld.shared.b32 %v3, [%sb+12];
    add.u64 %a, %ps, %t;
    st.global.b32 [%a], %v0; st.global.b32 [%a+4], %v1; st.global.b32 [%a+8], %v2; st.global.b32 [%a+12], %v3;
    ret;
}}
""")
            tail.append(f".buffer I{K} .u8 = {{ {h(inb.ljust(512, bytes(1)))} }};\n.buffer L{K} .u8 [{len(ldexp)}];\n.buffer S{K} .u8 [512];\n"
                        f".launch k{K} <<< 1, 32 >>> (I{K}, L{K}, S{K});\n.expect L{K} .u8 = {{ {h(ldexp)} }};\n"
                        f".expect S{K} .u8 = {{ {h((stexp).ljust(512, bytes(1))[:512])} }};")
            flush(); K += 1
# movmatrix
a = [random.randrange(2 ** 32) for _ in range(32)]
def elem(lane_regs, r, c):
    lane = r * 4 + c // 2
    return (lane_regs[lane] >> (16 * (c % 2))) & 0xffff
mv = []
for lane in range(32):
    g, t = lane // 4, lane % 4
    mv.append(elem(a, 2 * t, g) | (elem(a, 2 * t + 1, g) << 16))
out.append(f""".visible .entry k{K}(.param .u64 pi, .param .u64 po)
{{
    .reg .b64 %pi, %po, %t; .reg .b32 %tid, %v, %w;
    ld.param.u64 %pi, [pi]; ld.param.u64 %po, [po];
    mov.u32 %tid, %tid.x;
    mul.wide.u32 %t, %tid, 4;
    add.u64 %pi, %pi, %t; add.u64 %po, %po, %t;
    ld.global.b32 %v, [%pi];
    movmatrix.sync.aligned.m8n8.trans.b16 %w, %v;
    st.global.b32 [%po], %w;
    ret;
}}
""")
tail.append(f".buffer I{K} .u8 = {{ {h(b''.join(struct.pack('<I', x) for x in a))} }};\n.buffer O{K} .u8 [128];\n.launch k{K} <<< 1, 32 >>> (I{K}, O{K});\n.expect O{K} .u8 = {{ {h(b''.join(struct.pack('<I', x) for x in mv))} }};")
flush()
